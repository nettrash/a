#!/usr/bin/env python3
"""Generates `small.rs`: products and squares of 1 to 8 limbs in straight-line Rust.

    python3 small.py > small.rs

The output is as rustfmt leaves it.

Each kernel reads its operands into locals, then sums every column of the product in a
three-limb accumulator (Comba's order): `acc`, a `u128`, and `top`, the carries above it. LLVM
lowers a limb product to `mul`, `umulh`, `adds`, `adcs` and `cinc`. The code is written out in
full because the compiler does not unroll the triangular loops of the columns.
"""

MAX = 8

HEADER = '''//! Products and squares of a few limbs in registers, for the first steps of the doublings of the
//! Fibonacci and Lucas numbers and of the Lucas sequences. Generated by `small.py`; do not edit.
//!
//! The kernels of the multiplication are rows of limb products in inline assembly: at one to
//! eight limbs their passes' setup costs as much as the products themselves (a product of five
//! limbs by five took 52 cycles on an Apple M4 Max, about two a limb product, and a square of three
//! 17). Here the length is a constant, the operands are read into locals and every column of the
//! product is summed in a three-limb accumulator (Comba's order), the code written out in full: a
//! limb product is a `mul`, a `umulh` and three additions; a square sums the products of two
//! different limbs once, then doubles them and adds the squares of the limbs.

use super::super::mul::basecase;

/// The longest operands taken here; longer ones go to the multiplication's kernels.
pub(super) const MAX: usize = {MAX};

/// Adds `x y` to the column's sum `acc + top 2^128`.
#[inline(always)]
fn mac(acc: &mut u128, top: &mut u64, x: u64, y: u64) {{
    let (s, o) = acc.overflowing_add(u128::from(x) * u128::from(y));
    *acc = s;
    *top += u64::from(o);
}}

/// Sets limbs `k` and `k + 1` of `s` to the two doubled limbs `lo` and `hi` plus `x^2` and the
/// carry, which it updates.
#[inline(always)]
fn diagonal<const L: usize>(s: &mut [u64; L], k: usize, lo: u64, hi: u64, x: u64, carry: &mut u64) {{
    let d = u128::from(lo) | (u128::from(hi) << 64);
    let (v, o1) = d.overflowing_add(u128::from(x) * u128::from(x));
    let (v, o2) = v.overflowing_add(u128::from(*carry));
    s[k] = v as u64;
    s[k + 1] = (v >> 64) as u64;
    *carry = u64::from(o1) + u64::from(o2);
}}

/// The column's low limb, and the sum shifted down by a limb for the next column.
#[inline(always)]
fn next(acc: &mut u128, top: &mut u64) -> u64 {{
    let low = *acc as u64;
    *acc = (*acc >> 64) | (u128::from(*top) << 64);
    *top = 0;
    low
}}
'''

def mul_fn(n):
    out = []
    out.append(f'/// Sets the {2*n} limbs at `r` to the product of the {n} limbs at `a` and at `b`.')
    out.append('///')
    out.append('/// # Safety')
    out.append('///')
    out.append('/// The limbs at `a` and `b` must be valid for reads and those at `r` for writes; `r` may be')
    out.append('/// either, as the operands are read before anything is written.')
    out.append('#[inline(always)]')
    out.append(f'pub(super) unsafe fn mul_{n}(r: *mut u64, a: *const u64, b: *const u64) {{')
    out.append('    // SAFETY: as the caller guarantees.')
    out.append(f'    let (a, b) = unsafe {{ (a.cast::<[u64; {n}]>().read(), b.cast::<[u64; {n}]>().read()) }};')
    out.append('    let (mut acc, mut top) = (0u128, 0u64);')
    out.append(f'    let mut s = [0u64; {2*n}];')
    for k in range(2*n - 1):
        for i in range(n):
            j = k - i
            if 0 <= j < n:
                out.append(f'    mac(&mut acc, &mut top, a[{i}], b[{j}]);')
        out.append(f'    s[{k}] = next(&mut acc, &mut top);')
    out.append(f'    s[{2*n-1}] = acc as u64;')
    out.append('    // SAFETY: as the caller guarantees.')
    out.append(f'    unsafe {{ r.cast::<[u64; {2*n}]>().write(s) }};')
    out.append('}')
    return '\n'.join(out)

def sqr_fn(n):
    out = []
    out.append(f'/// Sets the {2*n} limbs at `r` to the square of the {n} limbs at `a`.')
    out.append('///')
    out.append('/// # Safety')
    out.append('///')
    out.append('/// As for the products.')
    out.append('#[inline(always)]')
    out.append(f'pub(super) unsafe fn sqr_{n}(r: *mut u64, a: *const u64) {{')
    out.append('    // SAFETY: as the caller guarantees.')
    out.append(f'    let a = unsafe {{ a.cast::<[u64; {n}]>().read() }};')
    if n == 1:
        out.append('    let p = u128::from(a[0]) * u128::from(a[0]);')
        out.append('    // SAFETY: as the caller guarantees.')
        out.append('    unsafe { r.cast::<[u64; 2]>().write([p as u64, (p >> 64) as u64]) };')
        out.append('}')
        return '\n'.join(out)
    out.append('    // The products of two different limbs once, by columns.')
    out.append('    let (mut acc, mut top) = (0u128, 0u64);')
    out.append(f'    let mut t = [0u64; {2*n}];')
    for k in range(1, 2*n - 2):
        for i in range(n):
            j = k - i
            if i < j < n:
                out.append(f'    mac(&mut acc, &mut top, a[{i}], a[{j}]);')
        out.append(f'    t[{k}] = next(&mut acc, &mut top);')
    out.append(f'    t[{2*n-2}] = acc as u64;')
    out.append('    // Doubled, with the squares of the limbs.')
    out.append(f'    let mut s = [0u64; {2*n}];')
    out.append('    let mut carry = 0u64;')
    for k in range(n):
        lo = f'(t[{2*k}] << 1) | (t[{2*k-1}] >> 63)' if k > 0 else f't[{2*k}] << 1'
        hi = f'(t[{2*k+1}] << 1) | (t[{2*k}] >> 63)'
        out.append(f'    let (lo, hi) = ({lo}, {hi});')
        out.append(f'    diagonal(&mut s, {2*k}, lo, hi, a[{k}], &mut carry);')
    out.append('    // SAFETY: as the caller guarantees.')
    out.append(f'    unsafe {{ r.cast::<[u64; {2*n}]>().write(s) }};')
    out.append('}')
    return '\n'.join(out)

def idx(n):
    """The index into the product of limb `i` of its top half: `i + n - 1`."""
    return 'i' if n == 1 else f'i + {n-1}'

def hi_fns():
    out = []
    for n in range(1, MAX+1):
        out.append('')
        out.append(f'/// Sets the {n} limbs at `r` to limbs {n-1} to {2*n-2} of the product of the {n} limbs at `a` and')
        out.append(f'/// at `b`: the product in fixed point with {n-1} limbs of fraction, rounded down.')
        out.append('///')
        out.append('/// # Safety')
        out.append('///')
        out.append('/// As for the products.')
        out.append('#[inline(always)]')
        out.append(f'unsafe fn mul_hi_{n}(r: *mut u64, a: *const u64, b: *const u64) {{')
        out.append(f'    let mut s = [0u64; {2*n}];')
        out.append('    // SAFETY: as the caller guarantees; the product is formed in `s` first.')
        out.append('    unsafe {')
        out.append(f'        mul_{n}(s.as_mut_ptr(), a, b);')
        out.append(f'        let hi: [u64; {n}] = core::array::from_fn(|i| s[{idx(n)}]);')
        out.append(f'        r.cast::<[u64; {n}]>().write(hi);')
        out.append('    }')
        out.append('}')
        out.append('')
        out.append(f'/// Sets the {n} limbs at `r` to limbs {n-1} to {2*n-2} of the square of the {n} limbs at `a`.')
        out.append('///')
        out.append('/// # Safety')
        out.append('///')
        out.append('/// As for the products.')
        out.append('#[inline(always)]')
        out.append(f'unsafe fn sqr_hi_{n}(r: *mut u64, a: *const u64) {{')
        out.append(f'    let mut s = [0u64; {2*n}];')
        out.append('    // SAFETY: as above.')
        out.append('    unsafe {')
        out.append(f'        sqr_{n}(s.as_mut_ptr(), a);')
        out.append(f'        let hi: [u64; {n}] = core::array::from_fn(|i| s[{idx(n)}]);')
        out.append(f'        r.cast::<[u64; {n}]>().write(hi);')
        out.append('    }')
        out.append('}')
    out.append('')
    out.append('/// Sets the `N` limbs at `r` to limbs `N - 1` to `2N - 2` of the product of the `N` limbs at `a`')
    out.append('/// and at `b`, `1 <= N <= MAX`: a fixed-point product with `N - 1` limbs of fraction.')
    out.append('///')
    out.append('/// # Safety')
    out.append('///')
    out.append('/// The limbs at `a` and `b` must be valid for reads and those at `r` for writes; `r` may be')
    out.append('/// either.')
    out.append('#[inline(always)]')
    out.append('pub(super) unsafe fn mul_hi<const N: usize>(r: *mut u64, a: *const u64, b: *const u64) {')
    out.append('    // SAFETY: forwarded; `N` is a constant, which picks one arm.')
    out.append('    unsafe {')
    out.append('        match N {')
    for n in range(1, MAX+1):
        out.append(f'            {n} => mul_hi_{n}(r, a, b),')
    out.append('            _ => unreachable!("a fixed-point product of more than MAX limbs"),')
    out.append('        }')
    out.append('    }')
    out.append('}')
    out.append('')
    out.append('/// Sets the `N` limbs at `r` to limbs `N - 1` to `2N - 2` of the square of the `N` limbs at `a`,')
    out.append('/// `1 <= N <= MAX`.')
    out.append('///')
    out.append('/// # Safety')
    out.append('///')
    out.append('/// As for [`mul_hi`].')
    out.append('#[inline(always)]')
    out.append('pub(super) unsafe fn sqr_hi<const N: usize>(r: *mut u64, a: *const u64) {')
    out.append('    // SAFETY: as for `mul_hi`.')
    out.append('    unsafe {')
    out.append('        match N {')
    for n in range(1, MAX+1):
        out.append(f'            {n} => sqr_hi_{n}(r, a),')
    out.append('            _ => unreachable!("a fixed-point square of more than MAX limbs"),')
    out.append('        }')
    out.append('    }')
    out.append('}')
    return '\n'.join(out)

def dispatch():
    out = []
    out.append('/// Sets the `2n` limbs at `r` to the square of the `n` limbs at `a`: here up to [`MAX`] limbs, and')
    out.append('/// by the schoolbook kernel beyond.')
    out.append('///')
    out.append('/// # Safety')
    out.append('///')
    out.append('/// `n >= 1`; the limbs at `a` must be valid for reads and those at `r` for writes, apart.')
    out.append('#[inline(never)]')
    out.append('pub(super) unsafe fn sqr(r: *mut u64, a: *const u64, n: usize) {')
    out.append('    // SAFETY: forwarded.')
    out.append('    unsafe {')
    out.append('        match n {')
    for n in range(1, MAX+1):
        out.append(f'            {n} => sqr_{n}(r, a),')
    out.append('            _ => basecase::sqr(r, a, n),')
    out.append('        }')
    out.append('    }')
    out.append('}')
    out.append('')
    out.append('/// Sets the `2n` limbs at `r` to the product of the `n` limbs at `a` and at `b`: here up to [`MAX`]')
    out.append('/// limbs, and by the schoolbook kernel beyond.')
    out.append('///')
    out.append('/// # Safety')
    out.append('///')
    out.append('/// `n >= 1`; the limbs at `a` and `b` must be valid for reads and those at `r` for writes, `r`')
    out.append('/// apart from both.')
    out.append('#[inline(never)]')
    out.append('pub(super) unsafe fn mul(r: *mut u64, a: *const u64, b: *const u64, n: usize) {')
    out.append('    // SAFETY: forwarded.')
    out.append('    unsafe {')
    out.append('        match n {')
    for n in range(1, MAX+1):
        out.append(f'            {n} => mul_{n}(r, a, b),')
    out.append('            _ => basecase::mul(r, a, b, n),')
    out.append('        }')
    out.append('    }')
    out.append('}')
    return '\n'.join(out)

print(HEADER.format(MAX=MAX))
print(dispatch())
for n in range(1, MAX+1):
    print()
    print(mul_fn(n))
for n in range(1, MAX+1):
    print()
    print(sqr_fn(n))
print(hi_fns())
