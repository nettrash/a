#!/usr/bin/env python3
"""Generates prime_chains.rs, the plans of the fixed powers of the prime fields:
python3 chains.py > prime_chains.rs. Each is the sliding-window plan of the exponent for the
window (of 2 to 8 bits) of the fewest operations, its table of odd powers counted."""
import sys

def plan(e, w):
    bits = bin(e)[2:]
    n = len(bits)
    def window(i):
        j = min(i + w, n)
        while bits[j - 1] == '0':
            j -= 1
        return j
    j = window(0)
    first = int(bits[:j], 2)
    i, pend, steps = j, 0, []
    while i < n:
        if bits[i] == '0':
            pend += 1
            i += 1
            continue
        j = window(i)
        steps.append((pend + (j - i), int(bits[i:j], 2)))
        pend, i = 0, j
    if pend:
        steps.append((pend, 0))
    top = max([first] + [v for _, v in steps])
    cost = sum(s for s, _ in steps) + sum(1 for _, v in steps if v) + 1 + (top - 1) // 2
    r = first
    for s, v in steps:
        r = (r << s) + v
    assert r == e
    return cost, first, steps, top

def emit(name, doc, e):
    cost, first, steps, top = min(plan(e, w) for w in range(2, 9))
    sq = sum(s for s, _ in steps)
    mul = sum(1 for _, v in steps if v)
    out = [f"/// {doc}:", f"/// {sq} squarings and {mul} products after the {(top + 1) // 2} odd powers to `x^{top}`, {cost}",
           "/// operations.",
           f"pub(super) const {name}: Chain = Chain {{",
           f"    top: {top},",
           f"    first: {first},",
           "    steps: &["]
    out += [f"        ({s}, {v})," for s, v in steps]
    out += ["    ],", "};"]
    return "\n".join(out)

BLS12_381 = 0x1a0111ea397fe69a4b1ba7b6434bacd764774b84f38512bf6730d2a0f6b0f6241eabfffeb153ffffb9feffffffffaaab

print('''//! The plans of the fixed powers of the prime fields. **This file is generated by `chains.py`,
//! next to it: change that, not this.**

use super::prime_sqrt::Chain;

/// BLS12-381's base prime, the low limb first.
pub(super) const BLS12_381_P: [u64; 6] = [
''' + "".join(f"    0x{(BLS12_381 >> (64 * i)) & ((1 << 64) - 1):016x},\n" for i in range(6)) + '''];
''')
print(emit("BLS12_381_SQRT", "`x^((p + 1)/4)` for BLS12-381's base prime `p`, a square root", (BLS12_381 + 1) // 4))
