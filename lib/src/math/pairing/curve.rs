//! The pairing-friendly curves: their parameters, generators and the constants of their
//! endomorphisms, computed once.

use super::g1::G1;
use super::g2::G2;
use super::gt::Gt;
use super::point::Jacobian;
use crate::math::field::{Fp, Fp2, Fp12, PrimeField, Tower};
use crate::math::numbers::{ByteOrder, Number};
use std::sync::OnceLock;

/// The family of a pairing-friendly curve, which decides its Miller loop and its final
/// exponentiation.
///
/// # Examples
///
/// ```
/// use a::math::pairing::{Family, PairingCurve};
///
/// assert_eq!(PairingCurve::bn254().family(), Family::Bn);
/// assert_eq!(PairingCurve::bls12_381().family(), Family::Bls12);
/// ```
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Family {
    /// Barreto–Naehrig: `p = 36x⁴ + 36x³ + 24x² + 6x + 1`, `r = 36x⁴ + 36x³ + 18x² + 6x + 1`,
    /// embedding degree 12; the optimal ate pairing loops over `6x + 2`.
    Bn,
    /// Barreto–Lynn–Scott of embedding degree 12: `r = x⁴ − x² + 1`,
    /// `p = (x − 1)² r / 3 + x`; the optimal ate pairing loops over `x`.
    Bls12,
}

/// The kind of the sextic twist `E': y² = x³ + b'` over `F_p²` that holds `G2`.
///
/// # Examples
///
/// ```
/// use a::math::field::Fp2;
/// use a::math::pairing::{PairingCurve, Twist};
///
/// let c = PairingCurve::bn254();
/// assert_eq!(c.twist(), Twist::D);
/// // b' = b/ξ on a D-type twist.
/// assert_eq!(&c.twist_b() * &c.tower().xi(), Fp2::from_base(c.tower(), c.b()));
/// ```
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Twist {
    /// "Divide": `b' = b / ξ`, with `(x, y) ↦ (x w², y w³)` onto the curve over `F_p¹²`. BN254.
    D,
    /// "Multiply": `b' = b ξ`, with `(x, y) ↦ (x / w², y / w³)`. BLS12-381.
    M,
}

/// A pairing-friendly curve `E: y² = x³ + b` over `F_p` with embedding degree 12: its groups `G1`
/// (points of `E(F_p)` of order `r`), `G2` (points of order `r` of the sextic twist `E'(F_p²)`)
/// and `GT` (the `r`-th roots of unity of `F_p¹²`), and the optimal ate pairing between them.
///
/// The curves are [`PairingCurve::bn254`] and [`PairingCurve::bls12_381`], built once; their points
/// borrow them, as the points of [`a::math::ec`](crate::math::ec) borrow their curve.
///
/// # Examples
///
/// ```
/// use a::math::pairing::{Family, PairingCurve, Twist};
/// use a::math::numbers::Number;
///
/// let c = PairingCurve::bls12_381();
/// assert_eq!(c.family(), Family::Bls12);
/// assert_eq!(c.twist(), Twist::M);
/// assert_eq!(c.x(), &Number::from(-0xd201_0000_0001_0000_i128));
/// assert!((c.g1_generator() * c.order()).is_identity());
/// assert!((c.g2_generator() * c.order()).is_identity());
/// ```
pub struct PairingCurve {
    /// The name.
    pub(super) name: &'static str,
    /// The family.
    pub(super) family: Family,
    /// The twist.
    pub(super) twist: Twist,
    /// The parameter `x` of the family, signed.
    pub(super) x: Number,
    /// The tower `F_p² → F_p⁶ → F_p¹²`.
    pub(super) tower: &'static Tower<'static>,
    /// The field of the scalars, of order `r`.
    pub(super) scalar: &'static PrimeField,
    /// `r`.
    pub(super) r: Number,
    /// `b`.
    pub(super) b: Fp<'static>,
    /// `b'`, of the twist.
    pub(super) b_twist: Fp2<'static>,
    /// `3b'`, for the doublings of the Miller loop.
    pub(super) b3_twist: Fp2<'static>,
    /// `1/2` in `F_p`.
    pub(super) half: Fp<'static>,
    /// The generator of `G1`.
    pub(super) g1: [Fp<'static>; 2],
    /// The generator of `G2`.
    pub(super) g2: [Fp2<'static>; 2],
    /// The cofactor of `G1` in `E(F_p)`.
    pub(super) h1: Number,
    /// The cofactor of `G2` in `E'(F_p²)`.
    pub(super) h2: Number,
    /// `ψ(x, y) = (x̄ · psi[0], ȳ · psi[1])`, the endomorphism of the twist that untwists, applies
    /// the Frobenius map and twists back.
    pub(super) psi: [Fp2<'static>; 2],
    /// `ψ²(x, y) = (x · psi2[0], y · psi2[1])`.
    pub(super) psi2: [Fp<'static>; 2],
    /// For BLS12-381, the cube root of unity `β` of `F_p` with `(βx, y) = [−x²](x, y)` on `G1`.
    pub(super) glv_beta: Option<Fp<'static>>,
    /// The scalar of the Miller loop: `6x + 2` for BN, `x` for BLS12.
    pub(super) loop_scalar: Number,
    /// The digits of `|loop_scalar|` in `{−1, 0, 1}`, least significant first.
    pub(super) loop_digits: Vec<i8>,
    /// The scalar `k` of the test `ψ(Q) = [k] Q` of membership in `G2`: `6x²` for BN, `x` for
    /// BLS12.
    pub(super) g2_test: Number,
}

impl PairingCurve {
    /// BN254, also alt_bn128 and BN256: the curve of Ethereum's precompiles (EIP-196, EIP-197),
    /// `y² = x³ + 3` over the 254-bit prime of [`PrimeField::bn254_base`], with
    /// `x = 4965661367192848881`, `G1` generated by `(1, 2)` of cofactor 1, and `G2` on the D-type
    /// twist `y² = x³ + 3/(9 + u)` with Ethereum's generator. About 100 bits of security since the
    /// number field sieve of Kim and Barbulescu (Barbulescu and Duquesne, *Updating key size
    /// estimations for pairings*, J. Cryptology 32, 2019).
    #[must_use]
    pub fn bn254() -> &'static PairingCurve {
        static C: OnceLock<PairingCurve> = OnceLock::new();
        C.get_or_init(|| {
            let x = Number::from(4_965_661_367_192_848_881_u64);
            PairingCurve::build(Parameters {
                name: "BN254",
                family: Family::Bn,
                twist: Twist::D,
                x,
                tower: Tower::bn254(),
                scalar: PrimeField::bn254_scalar(),
                b: 3,
                g1: ["1", "2"],
                g2: [
                    "10857046999023057135944570762232829481370756359578518086990519993285655852781",
                    "11559732032986387107991004021392285783925812861821192530917403151452391805634",
                    "8495653923123431417604973247489272438418190587263600148770280649306958101930",
                    "4082367875863433681332203403145435568316851327593401208105741076214120093531",
                ],
                radix: 10,
            })
        })
    }

    /// BLS12-381, of Zcash and Ethereum's consensus layer: `y² = x³ + 4` over the 381-bit prime of
    /// [`PrimeField::bls12_381_base`], with `x = −0xd201000000010000`, and `G2` on the M-type
    /// twist `y² = x³ + 4(1 + u)`, with the generators of the ZCash specification and the IETF
    /// draft on pairing-friendly curves. About 120 bits of security (Barbulescu and Duquesne).
    #[must_use]
    pub fn bls12_381() -> &'static PairingCurve {
        static C: OnceLock<PairingCurve> = OnceLock::new();
        C.get_or_init(|| {
            let x = -Number::from(0xd201_0000_0001_0000_u64);
            PairingCurve::build(Parameters {
                name: "BLS12-381",
                family: Family::Bls12,
                twist: Twist::M,
                x,
                tower: Tower::bls12_381(),
                scalar: PrimeField::bls12_381_scalar(),
                b: 4,
                g1: [
                    "17f1d3a73197d7942695638c4fa9ac0fc3688c4f9774b905a14e3a3f171bac586c55e83ff97a1aeffb3af00adb22c6bb",
                    "08b3f481e3aaa0f1a09e30ed741d8ae4fcf5e095d5d00af600db18cb2c04b3edd03cc744a2888ae40caa232946c5e7e1",
                ],
                g2: [
                    "024aa2b2f08f0a91260805272dc51051c6e47ad4fa403b02b4510b647ae3d1770bac0326a805bbefd48056c8c121bdb8",
                    "13e02b6052719f607dacd3a088274f65596bd0d09920b61ab5da61bbdc7f5049334cf11213945d57e5ac7d055d042b7e",
                    "0ce5d527727d6e118cc9cdc6da2e351aadfd9baa8cbdd3a76d429a695160d12c923ac9cc3baca289e193548608b82801",
                    "0606c4a02ea734cc32acd2b02bc28b99cb3e287e85a763af267492ab572e99ab3f370d275cec1da1aaa9075ff05f79be",
                ],
                radix: 16,
            })
        })
    }

    /// The curve from its parameters, with its constants derived and checked.
    fn build(c: Parameters) -> PairingCurve {
        let tower = c.tower;
        let fp = tower.base();
        let p = fp.modulus().clone();
        let x = &c.x;
        let one = Number::from(1u8);
        // p, r and the cofactors from x, checked against the fields.
        let (pp, r, h1, h2) = match c.family {
            Family::Bn => {
                let x2 = x * x;
                let x3 = &x2 * x;
                let x4 = &x3 * x;
                let pp = &x4 * 36u8 + &x3 * 36u8 + &x2 * 24u8 + x * 6u8 + 1u8;
                let r = &x4 * 36u8 + &x3 * 36u8 + &x2 * 18u8 + x * 6u8 + 1u8;
                let h2 = &pp * 2u8 - &r;
                (pp, r, one.clone(), h2)
            }
            Family::Bls12 => {
                let x2 = x * x;
                let r = &x2 * &x2 - &x2 + 1u8;
                let xm1 = x - 1u8;
                let pp = &xm1 * &xm1 * &r / 3u8 + x;
                let h1 = &xm1 * &xm1 / 3u8;
                let pw = |k: u32| x.pow(k);
                let h2 = (pw(8) - pw(7) * 4u8 + pw(6) * 5u8 - pw(4) * 4u8 + pw(3) * 6u8
                    - &x2 * 4u8
                    - x * 4u8
                    + 13u8)
                    / 9u8;
                (pp, r, h1, h2)
            }
        };
        assert!(
            pp == p && &r == c.scalar.modulus(),
            "the parameters of {}",
            c.name
        );
        let b = fp.from_u64(c.b);
        let b2 = Fp2::from_base(tower, b.clone());
        let b_twist = match c.twist {
            Twist::D => &b2 / &tower.xi(),
            Twist::M => &b2 * &tower.xi(),
        };
        let num = |s: &str| {
            Number::from_str_radix(s, c.radix, ByteOrder::LittleEndian).expect("a coordinate")
        };
        let g1 = [fp.element(&num(c.g1[0])), fp.element(&num(c.g1[1]))];
        let g2 = [
            Fp2::from_numbers(tower, &num(c.g2[0]), &num(c.g2[1])),
            Fp2::from_numbers(tower, &num(c.g2[2]), &num(c.g2[3])),
        ];
        // ψ: (x̄ γ, ȳ δ) with γ = ξ^((p − 1)/3), δ = ξ^((p − 1)/2) on a D-type twist, and their
        // inverses on an M-type one.
        let (gx, gy) = (
            tower.frobenius_coefficient(1, 2),
            tower.frobenius_coefficient(1, 3),
        );
        let psi = match c.twist {
            Twist::D => [gx, gy],
            Twist::M => [
                gx.inverse().expect("nonzero"),
                gy.inverse().expect("nonzero"),
            ],
        };
        let psi2 = [psi[0].norm(), psi[1].norm()];
        let loop_scalar = match c.family {
            Family::Bn => x * 6u8 + 2u8,
            Family::Bls12 => x.clone(),
        };
        let loop_digits = super::point::loop_digits(&loop_scalar);
        let g2_test = match c.family {
            Family::Bn => x * x * 6u8,
            Family::Bls12 => x.clone(),
        };
        let mut curve = PairingCurve {
            name: c.name,
            family: c.family,
            twist: c.twist,
            x: x.clone(),
            tower,
            scalar: c.scalar,
            r,
            b,
            b3_twist: &b_twist.double() + &b_twist,
            b_twist,
            half: fp.from_u64(2).inverse().expect("p is odd"),
            g1,
            g2,
            h1,
            h2,
            psi,
            psi2,
            glv_beta: None,
            loop_scalar,
            loop_digits,
            g2_test,
        };
        if c.family == Family::Bls12 {
            curve.glv_beta = Some(curve.find_glv_beta());
        }
        curve
    }

    /// The cube root of unity `β` with `(βx, y) = [−x²](x, y)` on `G1`: of the two, the one that
    /// does so on the generator.
    fn find_glv_beta(&self) -> Fp<'static> {
        let fp = self.tower.base();
        let root = (-fp.from_u64(3))
            .sqrt()
            .expect("−3 is a square as p ≡ 1 (mod 3)");
        let beta = (root - fp.one()) * fp.from_u64(2).inverse().expect("p is odd");
        let g = Jacobian::from_affine(self.g1[0].clone(), self.g1[1].clone());
        let want = g.mul(&(&self.x * &self.x)).neg();
        let phi = Jacobian {
            x: &g.x * &beta,
            y: g.y.clone(),
            z: g.z.clone(),
        };
        if phi.equals(&want) {
            beta
        } else {
            let other = beta.square();
            let phi = Jacobian {
                x: &g.x * &other,
                y: g.y.clone(),
                z: g.z.clone(),
            };
            assert!(phi.equals(&want), "no cube root of unity acts as −x²");
            other
        }
    }

    /// The name: `"BN254"` or `"BLS12-381"`.
    #[must_use]
    pub fn name(&self) -> &'static str {
        self.name
    }

    /// The family.
    #[must_use]
    pub fn family(&self) -> Family {
        self.family
    }

    /// The kind of the twist that holds `G2`.
    #[must_use]
    pub fn twist(&self) -> Twist {
        self.twist
    }

    /// The parameter `x` of the family, of which `p` and `r` are polynomials.
    #[must_use]
    pub fn x(&self) -> &Number {
        &self.x
    }

    /// The tower `F_p² → F_p⁶ → F_p¹²` of the coordinates of `G2` and the values of the pairing.
    #[must_use]
    pub fn tower(&self) -> &'static Tower<'static> {
        self.tower
    }

    /// The base field `F_p`.
    #[must_use]
    pub fn base_field(&self) -> &'static PrimeField {
        self.tower.base()
    }

    /// The field of the scalars, `F_r`.
    #[must_use]
    pub fn scalar_field(&self) -> &'static PrimeField {
        self.scalar
    }

    /// `r`, the prime order of `G1`, `G2` and `GT`.
    #[must_use]
    pub fn order(&self) -> &Number {
        &self.r
    }

    /// `b` of `E: y² = x³ + b`.
    #[must_use]
    pub fn b(&self) -> Fp<'static> {
        self.b.clone()
    }

    /// `b'` of the twist `E': y² = x³ + b'`: `b/ξ` (D-type) or `bξ` (M-type).
    #[must_use]
    pub fn twist_b(&self) -> Fp2<'static> {
        self.b_twist.clone()
    }

    /// The cofactor of `G1`: `#E(F_p) / r`, 1 for BN254 and `(x − 1)²/3` for BLS12-381.
    #[must_use]
    pub fn g1_cofactor(&self) -> &Number {
        &self.h1
    }

    /// The cofactor of `G2`: `#E'(F_p²) / r`, `2p − r` for BN254 and
    /// `(x⁸ − 4x⁷ + 5x⁶ − 4x⁴ + 6x³ − 4x² − 4x + 13)/9` for BLS12-381.
    #[must_use]
    pub fn g2_cofactor(&self) -> &Number {
        &self.h2
    }

    /// The scalar of the Miller loop of the optimal ate pairing: `6x + 2` for BN, `x` for BLS12.
    #[must_use]
    pub fn miller_loop_scalar(&self) -> &Number {
        &self.loop_scalar
    }

    /// The generator of `G1`.
    #[must_use]
    pub fn g1_generator(&self) -> G1<'_> {
        G1::from_jacobian(
            self,
            Jacobian::from_affine(self.g1[0].clone(), self.g1[1].clone()),
        )
    }

    /// The neutral element of `G1`, the point at infinity.
    #[must_use]
    pub fn g1_identity(&self) -> G1<'_> {
        G1::from_jacobian(self, Jacobian::identity(&self.b))
    }

    /// The generator of `G2`.
    #[must_use]
    pub fn g2_generator(&self) -> G2<'_> {
        G2::from_jacobian(
            self,
            Jacobian::from_affine(self.g2[0].clone(), self.g2[1].clone()),
        )
    }

    /// The neutral element of `G2`, the point at infinity.
    #[must_use]
    pub fn g2_identity(&self) -> G2<'_> {
        G2::from_jacobian(self, Jacobian::identity(&self.b_twist))
    }

    /// The neutral element of `GT`, 1.
    #[must_use]
    pub fn gt_identity(&self) -> Gt<'_> {
        Gt::from_fp12_unchecked(self, Fp12::one(self.tower))
    }

    /// `e(g₁, g₂)` of the two generators, which generates `GT`; computed once, when it is first
    /// asked for.
    #[must_use]
    pub fn gt_generator(&self) -> Gt<'_> {
        // Kept outside the curve, whose values are keys of hash sets: one curve of each family.
        static BN: OnceLock<Fp12<'static>> = OnceLock::new();
        static BLS12: OnceLock<Fp12<'static>> = OnceLock::new();
        let cell = match self.family {
            Family::Bn => &BN,
            Family::Bls12 => &BLS12,
        };
        let f = cell.get_or_init(|| {
            let e = self.pairing(&self.g1_generator(), &self.g2_generator());
            let c: Vec<Number> = e.value().coefficients().iter().map(Fp::value).collect();
            Fp12::from_coefficients(self.tower, &c)
        });
        Gt::from_fp12_unchecked(self, f.clone())
    }

    /// Whether two curves are the same.
    pub(super) fn same(&self, other: &PairingCurve) -> bool {
        core::ptr::eq(self, other) || self.name == other.name
    }

    /// Panics unless `other` is this curve.
    #[track_caller]
    pub(super) fn check(&self, other: &PairingCurve) {
        if !self.same(other) {
            different_curves();
        }
    }
}

impl core::fmt::Debug for PairingCurve {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.write_str(self.name)
    }
}

/// Panics for points of different curves.
#[cold]
#[inline(never)]
#[track_caller]
pub(super) fn different_curves() -> ! {
    panic!("the points are on different curves")
}

/// What a named curve is built from.
struct Parameters {
    name: &'static str,
    family: Family,
    twist: Twist,
    x: Number,
    tower: &'static Tower<'static>,
    scalar: &'static PrimeField,
    b: u64,
    /// The generator of `G1`, `x` and `y`, in `radix`.
    g1: [&'static str; 2],
    /// The generator of `G2`: `x₀, x₁, y₀, y₁`, in `radix`.
    g2: [&'static str; 4],
    radix: u32,
}
