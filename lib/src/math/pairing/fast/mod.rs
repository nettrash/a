//! The pairing's own arithmetic: `F_p`, `F_p²`, `F_p⁶` and `F_p¹²` of BN254 and BLS12-381 in
//! fixed arrays of 4 and 6 limbs, each prime and its Montgomery constants known at compile time,
//! the code instantiated once per curve. The public towers of
//! [`a::math::field`](crate::math::field) are general (any prime, any `β` and `ξ`) and pay for it
//! with a dispatch on the field's form at every operation and elements of nine limbs; the pairing,
//! its groups and their hashing compute here and convert at the public boundary, where the values
//! are the same elements of the same towers.
//!
//! [`Engine`] carries a curve's constants; [`with_engine!`] runs a block once for the engine of a
//! [`PairingCurve`], with the engine type and its number of limbs in scope.
//!
//! On aarch64 the field's sums, differences, Montgomery products and reductions and the
//! double-width products are `asm!` kernels (`aarch64.rs`, generated by `kernels.py`);
//! everywhere else, and under Miri, the portable code of `fp.rs` computes
//! the same values. Inversion is Lehmer's algorithm on the limbs (`inv.rs`).

