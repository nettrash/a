/// A curve's base field and tower, at compile time where it can be.
pub(crate) trait Engine<const N: usize>: Sized + 'static {
    /// `p`, the low limb first.
    const P: [u64; N];
    /// `−p⁻¹ mod 2⁶⁴`.
    const INV: u64;
    /// `R mod p`, `R = 2^(64 N)`: 1 in Montgomery's form.
    const R: [u64; N];
    /// `R² mod p`.
    const R2: [u64; N];
    /// `ξ = XI0 + u`: 9 + u on BN254, 1 + u on BLS12-381.
    const XI0: u64;

    /// The curve.
    fn curve() -> &'static PairingCurve;

    /// The constants computed once, on the first use.
    fn tables() -> &'static Tables<Self, N>;

    /// The constants of the groups' operations, computed once, on the first use.
    fn groups() -> &'static ops::GroupTables<Self, N>;

    /// The public base field.
    fn base_field() -> &'static PrimeField {
        Self::curve().tower.base()
    }
}

