/// Runs `$body` with `$e` the engine of the curve `$curve` and `$n` its number of limbs.
macro_rules! with_engine {
    ($curve:expr, $e:ident, $n:ident => $body:expr) => {
        match $curve.family {
            $crate::math::pairing::curve::Family::Bn => {
                type $e = $crate::math::pairing::fast::Bn;
                const $n: usize = 4;
                $body
            }
            $crate::math::pairing::curve::Family::Bls12 => {
                type $e = $crate::math::pairing::fast::Bls;
                const $n: usize = 6;
                $body
            }
        }
    };
}
pub(crate) use with_engine;

/// The constants of an engine that are computed, once.
pub(crate) struct Tables<E, const N: usize> {
    /// `frob[k][i] = ξ^(i (pᵏ − 1)/6)`, the public tower's Frobenius coefficients.
    pub(crate) frob: [[Fp2<E, N>; 6]; 12],
    /// `1/2`.
    pub(crate) half: Fp<E, N>,
    /// `(p + 1)/4`, the exponent of square roots.
    pub(crate) sqrt_exp: [u64; N],
    /// `(p − 1)/2`, the exponent of the Legendre symbol.
    pub(crate) legendre_exp: [u64; N],
    /// `b` of the curve and `b'` of the twist, and `3b'`.
    pub(crate) b: Fp<E, N>,
    pub(crate) b_twist: Fp2<E, N>,
    pub(crate) b3_twist: Fp2<E, N>,
    /// ψ's constants `(γₓ, γᵧ)` and `ψ²`'s `(γₓ γ̄ₓ, γᵧ γ̄ᵧ)` (elements of `F_p`).
    pub(crate) psi: [Fp2<E, N>; 2],
    pub(crate) psi2: [Fp<E, N>; 2],
    /// The signed digits of the Miller loop's scalar, least significant first.
    pub(crate) loop_digits: Vec<i8>,
    /// Whether the loop's scalar is negative.
    pub(crate) loop_negative: bool,
    /// The signed digits of `|x|`, least significant first, its top digit 1, and the sign of `x`.
    pub(crate) x_digits: Vec<i8>,
    pub(crate) x_negative: bool,
    /// The signed digits of `r`.
    pub(crate) r_digits: Vec<i8>,
    /// `R³ mod p` as raw limbs: a product by it takes `t/R` to `tR`.
    pub(crate) r3: Fp<E, N>,
}

/// The limbs of a nonnegative number below `2^(64 N)`.
pub(crate) fn limbs<const N: usize>(x: &Number) -> [u64; N] {
    let mut b = x.value.clone();
    if x.byte_order == ByteOrder::BigEndian {
        b.reverse();
    }
    let mut l = [0u64; N];
    for (i, chunk) in b.chunks(8).enumerate().take(N) {
        let mut w = [0u8; 8];
        w[..chunk.len()].copy_from_slice(chunk);
        l[i] = u64::from_le_bytes(w);
    }
    l
}

/// The digits of `|e|` the public tower's cyclotomic powers take: the non-adjacent form when it
/// has fewer nonzero digits than the binary form, else the binary form.
pub(crate) fn signed_digits(e: &Number) -> Vec<i8> {
    let e = e.abs();
    let mut naf = Vec::new();
    let mut k = e.clone();
    let four = Number::from(4u8);
    while !k.is_zero() {
        if k.bit(0) {
            let d: i8 = if k.rem_euclid(&four) == 1u8 { 1 } else { -1 };
            k = if d == 1 { k - 1u8 } else { k + 1u8 };
            naf.push(d);
        } else {
            naf.push(0);
        }
        k >>= 1usize;
    }
    let weight = naf.iter().filter(|&&d| d != 0).count() as u64;
    if weight < e.count_ones() {
        naf
    } else {
        (0..e.bits()).map(|i| i8::from(e.bit(i))).collect()
    }
}

impl<E: Engine<N>, const N: usize> Tables<E, N> {
    fn build() -> Tables<E, N> {
        let c = E::curve();
        let t = c.tower;
        let p = t.base().modulus();
        let mut frob = [[Fp2::zero(); 6]; 12];
        for (k, row) in frob.iter_mut().enumerate() {
            for (i, x) in row.iter_mut().enumerate() {
                *x = Fp2::from_public(&t.frobenius_coefficient(k, i));
            }
        }
        Tables {
            frob,
            half: Fp::from_public(&c.half),
            sqrt_exp: limbs(&((p + 1u8) >> 2usize)),
            legendre_exp: limbs(&((p - 1u8) >> 1usize)),
            b: Fp::from_public(&c.b),
            b_twist: Fp2::from_public(&c.b_twist),
            b3_twist: Fp2::from_public(&c.b3_twist),
            psi: [Fp2::from_public(&c.psi[0]), Fp2::from_public(&c.psi[1])],
            psi2: [Fp::from_public(&c.psi2[0]), Fp::from_public(&c.psi2[1])],
            loop_digits: c.loop_digits.clone(),
            loop_negative: c.loop_scalar.is_negative(),
            x_digits: signed_digits(&c.x),
            x_negative: c.x.is_negative(),
            r_digits: signed_digits(&c.r),
            r3: Fp::from_canonical(E::R2),
        }
    }
}

impl<E: Engine<N>, const N: usize> Fp<E, N> {
    /// The element of a public one of the curve's base field: its Montgomery limbs as they are
    /// (the public field holds `xR mod p` with the same `R = 2^(64 N)`), or its bytes for a field
    /// in another form.
    #[inline]
    pub(crate) fn from_public(x: &field::Fp<'_>) -> Self {
        if let Some(l) = x.montgomery()
            && l.len() == N
        {
            let mut a = [0u64; N];
            a.copy_from_slice(l);
            return Self::raw(a);
        }
        Self::from_le_bytes(&x.to_bytes_le())
    }

    /// The public element: from the Montgomery limbs, without leaving the Montgomery domain, or
    /// through the canonical bytes for a field in another form.
    #[inline]
    pub(crate) fn to_public(self) -> field::Fp<'static> {
        if let Some(x) = field::Fp::from_montgomery(E::base_field(), &self.0) {
            return x;
        }
        // The canonical limbs as bytes on the stack: 8N ≤ 48.
        let c = self.canonical();
        let mut b = [0u8; 48];
        for (i, l) in c.iter().enumerate() {
            b[8 * i..8 * i + 8].copy_from_slice(&l.to_le_bytes());
        }
        E::base_field()
            .from_bytes_le(&b[..8 * N])
            .expect("an element below p")
    }
}

impl<E: Engine<N>, const N: usize> Fp2<E, N> {
    /// The element of a public one of the curve's tower.
    pub(crate) fn from_public(x: &field::Fp2<'_>) -> Self {
        Fp2::new(Fp::from_public(x.c0()), Fp::from_public(x.c1()))
    }

    /// The public element: from the coefficients' Montgomery limbs when the base field holds its
    /// elements so.
    #[inline]
    pub(crate) fn to_public(self) -> field::Fp2<'static> {
        let t = E::curve().tower;
        field::Fp2::from_montgomery(t, &self.c0.0, &self.c1.0)
            .unwrap_or_else(|| field::Fp2::new(t, self.c0.to_public(), self.c1.to_public()))
    }
}

impl<E: Engine<N>, const N: usize> Fp12<E, N> {
    /// The element of a public one of the curve's tower.
    pub(crate) fn from_public(x: &field::Fp12<'_>) -> Self {
        let c = x.coefficients();
        Fp12::from_coefficients(&core::array::from_fn(|i| Fp::from_public(&c[i])))
    }

    /// The public element.
    pub(crate) fn to_public(self) -> field::Fp12<'static> {
        let c = self.coefficients();
        let e = |i: usize| Fp2::new(c[i], c[i + 1]).to_public();
        field::Fp12::new(
            field::Fp6::new(e(0), e(2), e(4)),
            field::Fp6::new(e(6), e(8), e(10)),
        )
    }
}
