"""Tables of Ai, Ai', Bi, Bi' (airy/tables.rs): asymptotic forms in t = 1/ζ for x ≥ 4 and
x ≤ −8 (modulus and phase), expansions about the zeros on [−8.x, ~0], plain pieces up to 4.
Run here: python3 gen_airy.py > tables.rs && rustfmt --edition 2024 tables.rs"""

import sys

sys.dont_write_bytecode = True  # no __pycache__ beside the sources


import os
import sys

import mpmath
from mpmath import mpf

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "bessel"))
from remez import fit  # noqa: E402  (the shared Remez fitter, ../bessel/remez.py)
from airy_post import post  # noqa: E402

mp = mpmath.mp
mp.prec = 160
PI = mpmath.pi
TARGET = 2.0 ** -61
# A plain piece also meets this with its coefficients rounded to f64 (the first two kept as
# double-doubles), else it is halved: on the widest ones, at whose ends c₂u² and c₃u³ reach the
# size of the value, the rounding alone cost up to 0.85 ulp (Bi′ on [−1.17, −0.087]).
FINAL = 2.0 ** -57
LOG = sys.stderr
XP = mpf(4)       # asymptotic from here on (x ≥ XP)
XN = mpf(8)       # modulus/phase for x ≤ −XN... (beyond the zero tables)
XPB = mpf(12)     # Bi, Bi′: asymptotic from here on (its subdominant part spoils a fit below)
XPOS = {'ai': XP, 'aip': XP, 'bi': XPB, 'bip': XPB}
out = []
w = out.append
w("// Generated by src/math/special/airy/gen_airy.py (mpmath, Remez): do not edit. Run there:\n// python3 gen_airy.py > tables.rs && rustfmt --edition 2024 tables.rs\n")
w("#![allow(clippy::excessive_precision, clippy::unreadable_literal)]\n\n")


def ddl(coef, k):
    o = []
    for i, v in enumerate(coef):
        if i < k:
            h = float(v)
            o += [h, float(v - h)]
        else:
            o.append(float(v))
    return o


def arr(name, vals, doc):
    w(f"/// {doc}\npub(super) const {name}: [f64; {len(vals)}] = [\n")
    for v in vals:
        w(f"    {v!r},\n")
    w("];\n")


def arr2(name, rows, doc):
    n = max(len(r) for r in rows)
    w(f"/// {doc}\npub(super) const {name}: [[f64; {n}]; {len(rows)}] = [\n")
    for r in rows:
        w("    [\n")
        for v in list(r) + [0.0] * (n - len(r)):
            w(f"        {v!r},\n")
        w("    ],\n")
    w("];\n")


F = {
    'ai': lambda x: mpmath.airyai(x), 'aip': lambda x: mpmath.airyai(x, 1),
    'bi': lambda x: mpmath.airybi(x), 'bip': lambda x: mpmath.airybi(x, 1),
}
D = {
    'ai': lambda x: mpmath.airyai(x, 1), 'aip': lambda x: x * mpmath.airyai(x),
    'bi': lambda x: mpmath.airybi(x, 1), 'bip': lambda x: x * mpmath.airybi(x),
}


def zeros(name, n):
    if name == 'ai':
        return [mpmath.airyaizero(k) for k in range(1, n + 1)]
    if name == 'aip':
        return [mpmath.airyaizero(k, 1) for k in range(1, n + 1)]
    if name == 'bi':
        return [mpmath.airybizero(k) for k in range(1, n + 1)]
    return [mpmath.airybizero(k, 1) for k in range(1, n + 1)]


# The extrema: Ai's are the zeros of Ai′, Ai′'s the zeros of Ai (and 0), and the same for Bi.
EXT = {'ai': ('aip', False), 'aip': ('ai', True), 'bi': ('bip', True), 'bip': ('bi', False)}


def plain_pieces(f, lo, hi, name, maxdeg=16):
    """Pieces [a, b] of [lo, hi], each a Remez fit in u = x − a, halved until the degree fits."""
    todo = [(mpf(lo), mpf(hi))]
    rows = []
    while todo:
        a, b = todo.pop(0)
        ok = None
        for deg in range(6, maxdeg + 1):
            cf, err, e2, mpc = fit(lambda u, a=a: f(a + u), 0, b - a, deg, center=0, grid=400,
                                   exact=2, want_mp=True)
            if e2 < TARGET and err < FINAL:
                ok = (deg, err, e2, mpc)
                break
        if ok is None:
            m = (a + b) / 2
            todo = [(a, m), (m, b)] + todo
            continue
        print(f"{name} plain [{float(a):.4f},{float(b):.4f}] deg {ok[0]} fit {ok[2]:.2e} "
              f"final {ok[1]:.2e}", file=LOG)
        rows.append((a, b, [float(a)] + ddl(ok[3], 2)))
    rows.sort(key=lambda r: r[0])
    return rows


def zero_fit(f, df, z, lo, hi, name):
    q = lambda d: f(z + d) / d if abs(d) > mpf(10) ** -30 else df(z)
    c0 = df(z)
    for deg in range(8, 24):
        cf, err, e2, mpc = fit(q, lo - z, hi - z, deg, center=0, grid=500,
                               basis=list(range(1, deg + 1)), fixed={0: c0}, exact=1,
                               want_mp=True)
        if e2 < TARGET:
            break
    print(f"{name} z={float(z):.6f} [{float(lo):.4f},{float(hi):.4f}] deg {deg} fit {e2:.2e} "
          f"final {err:.2e}", file=LOG)
    h = float(c0)
    return [h, float(c0 - h)] + ddl(mpc, 1)


for name in ('ai', 'aip', 'bi', 'bip'):
    f, df = F[name], D[name]
    zs = zeros(name, 12)
    other, with0 = EXT[name]
    ext = zeros(other, 13)
    if with0:
        ext = [mpf(0)] + ext
    # The plain region starts at the first extremum below the first zero... (to the right of it).
    right = [e for e in ext if e > zs[0]]
    start = min(right) if right else mpf(0)
    # The plain region: [start, 1]; then e^(±ζ)·f on [1, XP].
    rows = plain_pieces(f, start, mpf(1), name)
    sg = 1 if name in ('ai', 'aip') else -1
    rows2 = plain_pieces(lambda x: f(x) * mpmath.exp(sg * mpf(2) / 3 * x ** mpf(1.5)), mpf(1),
                         XPOS[name], name + " scaled")
    rows = rows + rows2
    U = name.upper()
    arr2(f"{U}_P", [r[2] for r in rows],
         f"`{name}` on pieces of `[{float(start):.4f}, 1]`, then `e^(±ζ)·{name}` on pieces of `[1, 4]`: "
         "`[x₀, c₀ hi, c₀ lo, c₁ hi, c₁ lo, c₂, …]`.")
    arr(f"{U}_PB", [float(r[0]) for r in rows] + [float(XPOS[name])],
        f"The bounds of the pieces of `{name}`.")
    # Zero intervals down past −XN.
    bounds = [start]
    crow = []
    zz = []
    for z in zs:
        lo = max([e for e in ext if e < z])
        hi = bounds[-1]
        crow.append(zero_fit(f, df, z, lo, hi, name))
        h = float(z)
        zz.append([h, float(z - h)])
        bounds.append(lo)
        if lo < -XN:
            break
    arr(f"{U}_ZB", [float(b) for b in bounds],
        f"The bounds of the intervals of `{name}` about its zeros, from 0 down.")
    arr2(f"{U}_Z", zz, f"The zeros of `{name}` in the intervals (double-double).")
    arr2(f"{U}_C", crow, f"`{name}(z + d)/d` about each zero: `[c₀ hi, c₀ lo, c₁ hi, c₁ lo, c₂, …]`.")

# Positive asymptotic forms, t = 1/ζ ∈ [0, 1/ζ(XPOS)].
zeta = lambda x: mpf(2) / 3 * x ** mpf(1.5)
SP = mpmath.sqrt(PI)
G = {
    'ai': lambda x: mpmath.airyai(x) * 2 * SP * x ** mpf(0.25) * mpmath.exp(zeta(x)),
    'aip': lambda x: -mpmath.airyai(x, 1) * 2 * SP * x ** mpf(-0.25) * mpmath.exp(zeta(x)),
    'bi': lambda x: mpmath.airybi(x) * SP * x ** mpf(0.25) * mpmath.exp(-zeta(x)),
    'bip': lambda x: mpmath.airybi(x, 1) * SP * x ** mpf(-0.25) * mpmath.exp(-zeta(x)),
}
LEAD = {'ai': -mpf(5) / 72, 'aip': mpf(7) / 72, 'bi': mpf(5) / 72, 'bip': -mpf(7) / 72}
for name in ('ai', 'aip', 'bi', 'bip'):
    TP = 1 / zeta(XPOS[name])
    g = G[name]
    xt = lambda t: (3 / (2 * t)) ** (mpf(2) / 3)
    fn = lambda t: (g(xt(t)) - 1) / t if t > mpf(10) ** -12 else LEAD[name]
    for deg in range(4, 30):
        cf, err, e2, mpc = fit(fn, mpf(0), TP, deg, center=0, grid=400, rel=False, exact=1,
                               want_mp=True)
        if e2 * float(TP) < 2.0 ** -62:
            break
    print(f"{name} pos asympt deg {deg} abs {e2 * float(TP):.2e}", file=LOG)
    arr(f"{name.upper()}_A", ddl(mpc, 1),
        f"`({name} scaled − 1)/t`, `t = 1/ζ ≤ 1/ζ(4)`: `[c₀ hi, c₀ lo, c₁, …]` in `t`.")

# Negative side: Ai(−y) = M cos θ, Bi(−y) = M sin θ, θ = π/4 − ζ + α;
# Ai′(−y) = N cos φ, Bi′(−y) = N sin φ, φ = 3π/4 − ζ + β.
TN = 1 / zeta(XN)


def modphase(y, deriv):
    if deriv:
        a, b = mpmath.airyai(-y, 1), mpmath.airybi(-y, 1)
        base = 3 * PI / 4 - zeta(y)
        scale = SP * y ** mpf(-0.25)
    else:
        a, b = mpmath.airyai(-y), mpmath.airybi(-y)
        base = PI / 4 - zeta(y)
        scale = SP * y ** mpf(0.25)
    m = mpmath.sqrt(a * a + b * b)
    th = mpmath.atan2(b, a)
    al = th - base
    al = al - 2 * PI * mpmath.nint(al / (2 * PI))
    return m * scale, al


for deriv, nm in ((False, 'M'), (True, 'N')):
    yt = lambda t: (3 / (2 * t)) ** (mpf(2) / 3)
    TMIN = mpf(10) ** -5
    fm = lambda t: (modphase(yt(t), deriv)[0] - 1) / (t * t)
    fa = lambda t: modphase(yt(t), deriv)[1] / t
    for deg in range(3, 14):
        cfm, errm, e2m, mpm = fit(fm, TMIN, TN, 2 * deg, center=0, grid=300, rel=False,
                                  basis=[2 * i for i in range(deg + 1)], want_mp=True)
        if e2m * float(TN) ** 2 < 2.0 ** -64:
            break
    print(f"{nm} deg {deg} abs {e2m * float(TN) ** 2:.2e}", file=LOG)
    for deg in range(3, 14):
        cfa, erra, e2a, mpa = fit(fa, TMIN, TN, 2 * deg, center=0, grid=300, rel=False,
                                  basis=[2 * i for i in range(deg + 1)], want_mp=True)
        if e2a * float(TN) < 2.0 ** -70:
            break
    print(f"{nm} phase deg {deg} abs {e2a * float(TN):.2e}", file=LOG)
    arr(f"{nm}_MOD", cfm, f"`({nm}(y)·√π·y^(∓1/4) − 1)/t²`, `t = 1/ζ ≤ 1/ζ(8)`, in `t²`.")
    arr(f"{nm}_PHASE", cfa, f"The phase correction over `t`, in `t²`.")
w(f"/// `x` of the positive forms, `−x` of the modulus and phase.\n")
w(f"pub(super) const X_POS: f64 = {float(XP)!r};\npub(super) const X_POS_B: f64 = {float(XPB)!r};\n")
sys.stdout.write(post("".join(out)))
