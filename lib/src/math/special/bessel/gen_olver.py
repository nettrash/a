"""Tables of the uniform expansions for large orders (tables_olver.rs): Debye's polynomials U_k,
and for Olver's expansion the Taylor
coefficients about z = 1 (w = 1 − z) of ζ(z)/w, of φ(z) = (4ζ/(1 − z²))^(1/4) and of B₀(ζ(z)), and
atan at the points of its reduction. Run here:
python3 gen_olver.py > tables_olver.rs && rustfmt --edition 2024 tables_olver.rs"""

import sys
import mpmath
from mpmath import mpf

mp = mpmath.mp
mp.prec = 600
N = 18


def zeta(z):
    if z < 1:
        s = mpmath.sqrt(1 - z * z)
        f = mpmath.log((1 + s) / z) - s
        return (mpf(3) / 2 * f) ** (mpf(2) / 3)
    s = mpmath.sqrt(z * z - 1)
    f = s - mpmath.atan(s)
    return -(mpf(3) / 2 * f) ** (mpf(2) / 3)


def b0(z):
    c = zeta(z)
    if z < 1:
        s = mpmath.sqrt(1 - z * z)
        return -mpf(5) / (48 * c * c) + (5 / (24 * s ** 3) - 1 / (8 * s)) / mpmath.sqrt(c)
    s = mpmath.sqrt(z * z - 1)
    return -mpf(5) / (48 * c * c) + (5 / (24 * s ** 3) + 1 / (8 * s)) / mpmath.sqrt(-c)


def taylor(f, n):
    # Chebyshev interpolation on |w| ≤ 0.06 (f analytic there), then monomials: exact enough at
    # 600 bits with the singular points avoided.
    h = mpf("0.06")
    m = n + 8
    xs = [h * mpmath.cos(mpmath.pi * (k + mpf(1) / 2) / m) for k in range(m)]
    A = mpmath.matrix([[x ** j for j in range(m)] for x in xs])
    c = mpmath.lu_solve(A, mpmath.matrix([f(x) for x in xs]))
    return [c[j] for j in range(n)]


out = []
w = out.append
w("// Generated by src/math/special/bessel/gen_olver.py (mpmath): do not edit. Run there:\n")
w("// python3 gen_olver.py > tables_olver.rs && rustfmt --edition 2024 tables_olver.rs\n")
w("#![allow(clippy::approx_constant, clippy::excessive_precision, clippy::unreadable_literal)]\n\n")


def arr(name, vals, doc):
    w(f"/// {doc}\npub(super) const {name}: [f64; {len(vals)}] = [\n")
    for v in vals:
        w(f"    {float(v)!r},\n")
    w("];\n")


arr("ZW", taylor(lambda u: zeta(1 - u) / u, N), "`ζ(1 − w)/w` in powers of `w`, `|w| ≤ 0.06`.")
arr("PHI", taylor(lambda u: (4 * zeta(1 - u) / (u * (2 - u))) ** (mpf(1) / 4), N),
    "`φ = (4ζ/(1 − z²))^(1/4)` in powers of `w = 1 − z`.")
arr("B0", taylor(lambda u: b0(1 - u), N), "`B₀(ζ)` in powers of `w = 1 − z`.")
pts = [mpf(k) / 8 for k in range(9)]
w("/// `atan(k/8)` as double-doubles, `k = 0..=8`.\npub(super) const ATAN8: [[f64; 2]; 9] = [\n")
for p in pts:
    a = mpmath.atan(p)
    h = float(a)
    w(f"    [{h!r}, {float(a - h)!r}],\n")
w("];\n")
# Debye's polynomials U_k(p), k = 1..12, by U_(k+1) = p²(1 − p²)U_k′/2 + (1/8)∫₀ᵖ (1 − 5t²)U_k:
# row k − 1 holds the coefficients of p^k, p^(k+2), …, p^(3k).
from fractions import Fraction


def _mul(a, b):
    r = {}
    for e1, c1 in a.items():
        for e2, c2 in b.items():
            r[e1 + e2] = r.get(e1 + e2, 0) + c1 * c2
    return r


U = [{0: Fraction(1)}]
for k in range(12):
    u = U[-1]
    a = _mul({2: Fraction(1, 2), 4: Fraction(-1, 2)}, {e - 1: c * e for e, c in u.items() if e})
    b = {e + 1: c / (e + 1) for e, c in _mul({0: Fraction(1), 2: Fraction(-5)}, u).items()}
    r = dict(a)
    for e, c in b.items():
        r[e] = r.get(e, 0) + c / 8
    U.append({e: c for e, c in r.items() if c != 0})
w("/// Debye's polynomials: row `k − 1` the coefficients of `p^k, p^(k+2), …, p^(3k)` of `U_k(p)`.\n")
w("pub(super) const DEBYE_U: [[f64; 13]; 12] = [\n")
for k in range(1, 13):
    row = [float(U[k].get(k + 2 * j, 0)) for j in range(k + 1)] + [0.0] * (12 - k)
    w("    [" + ", ".join(repr(v) for v in row) + "],\n")
w("];\n")
# Debye's exponent eta(z) = sqrt(1 + z²) + ln(z/(1 + sqrt(1 + z²))) vanishes at z0 = 0.6627…
# (Laplace's limit): the bits of z0 after the binary point (for x − z0·ν exactly), and its Taylor
# coefficients eta^(k)(z0)/k!, k = 1..16, the first three as double-doubles.
with mpmath.workprec(1600):
    def eta(z):
        s = mpmath.sqrt(1 + z * z)
        return s + mpmath.log(z / (1 + s))

    z0 = mpmath.findroot(eta, mpf("0.66274341934918158"))
    assert abs(eta(z0)) < mpf(2) ** -1500
    nw = 18
    zb = int(mpmath.floor(z0 * mpf(2) ** (64 * nw)))
    w("/// The bits of `z₀ = 0.6627…`, the root of Debye's `η(z) = √(1 + z²) + ln(z/(1 + √(1 + z²)))`\n")
    w(f"/// (Laplace's limit), after the binary point: {64 * nw} of them.\n")
    w(f"pub(super) const Z0_BITS: [u64; {nw}] = [\n")
    for i in range(nw):
        w(f"    0x{(zb >> (64 * (nw - 1 - i))) & ((1 << 64) - 1):016x},\n")
    w("];\n")
    c = mpmath.taylor(eta, z0, 16)
    w("/// `η^(k)(z₀)/k!` for `k = 1..=3` as double-doubles, then `k = 4..=16`.\n")
    w("pub(super) const ETA_Z0_DD: [[f64; 2]; 3] = [\n")
    for k in range(1, 4):
        h = float(c[k])
        w(f"    [{h!r}, {float(c[k] - h)!r}],\n")
    w("];\n")
    arr("ETA_Z0", [c[k] for k in range(4, 17)], "`η^(k)(z₀)/k!` for `k = 4..=16`.")
    # eta(z) + z vanishes at z1 = 0.4477…: about x = z1·ν the term e^(−x)·K_ν(x) of the scaled
    # reflection of I is within the range. Its bits and the Taylor coefficients of eta(z) + z
    # about z1 likewise (the first three as double-doubles).
    z1 = mpmath.findroot(lambda z: eta(z) + z, mpf("0.4477432"))
    assert abs(eta(z1) + z1) < mpf(2) ** -1500
    zb = int(mpmath.floor(z1 * mpf(2) ** (64 * nw)))
    w("/// The bits of `z₁ = 0.4477…`, the root of `η(z) + z` (`η` as for `z₀`), after the binary\n")
    w(f"/// point: {64 * nw} of them.\n")
    w(f"pub(super) const Z1_BITS: [u64; {nw}] = [\n")
    for i in range(nw):
        w(f"    0x{(zb >> (64 * (nw - 1 - i))) & ((1 << 64) - 1):016x},\n")
    w("];\n")
    c = mpmath.taylor(lambda z: eta(z) + z, z1, 17)
    # The series is used for |D| ≤ 1300 from ν = 2¹⁶ on, |u| = |D|/ν ≤ 0.02 (the result is in
    # range only for |D| below about 250): the first term left out, ν·c₁₇·u¹⁷, below 2⁻⁶⁰ there.
    assert abs(c[17]) * mpf("0.0199") ** 17 * 2 ** 16 < mpf(2) ** -60
    w("/// `(η + z)^(k)(z₁)/k!` for `k = 1..=3` as double-doubles, then `k = 4..=16`.\n")
    w("pub(super) const ETA_Z1_DD: [[f64; 2]; 3] = [\n")
    for k in range(1, 4):
        h = float(c[k])
        w(f"    [{h!r}, {float(c[k] - h)!r}],\n")
    w("];\n")
    arr("ETA_Z1", [c[k] for k in range(4, 17)], "`(η + z)^(k)(z₁)/k! = η^(k)(z₁)/k!` for `k = 4..=16`.")
    w(f"/// `z₁` rounded to `f64`.\npub(super) const Z1_HI: f64 = {float(z1)!r};\n")
sys.stdout.write("".join(out))
