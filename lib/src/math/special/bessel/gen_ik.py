import sys
import mpmath
from mpmath import mpf
from remez import fit

mp = mpmath.mp
mp.prec = 160
PI = mpmath.pi
TARGET = 2.0 ** -60
LOG = sys.stderr
out = []
w = out.append
w("// Generated by src/math/special/bessel/gen_ik.py (mpmath, Remez): do not edit. Run there:\n// python3 gen_ik.py > tables_ik.rs && rustfmt --edition 2024 tables_ik.rs\n")
w("#![allow(clippy::excessive_precision, clippy::unreadable_literal)]\n\n")


def arr(name, vals, doc):
    w(f"/// {doc}\npub(super) const {name}: [f64; {len(vals)}] = [\n")
    for v in vals:
        w(f"    {v!r},\n")
    w("];\n")


def arr2(name, rows, doc):
    n = max(len(r) for r in rows)
    w(f"/// {doc}\npub(super) const {name}: [[f64; {n}]; {len(rows)}] = [\n")
    for r in rows:
        w("    [\n")
        for v in list(r) + [0.0] * (n - len(r)):
            w(f"        {v!r},\n")
        w("    ],\n")
    w("];\n")


def ddl(coef, k=2):
    """The first k coefficients as (hi, lo) pairs, then the rest as floats."""
    out = []
    for i, v in enumerate(coef):
        if i < k:
            h = float(v)
            out += [h, float(v - h)]
        else:
            out.append(float(v))
    return out


def best(f, a, b, basis_fn, name, maxdeg=24, rel=True, fixed=None, mindeg=4, k=2):
    for deg in range(mindeg, maxdeg + 1):
        cf, err, e2, mpc = fit(f, a, b, deg, center=0, grid=400, basis=basis_fn(deg), rel=rel,
                               fixed=fixed, exact=2, want_mp=True)
        if e2 < TARGET:
            print(f"{name} [{float(a):.5g},{float(b):.5g}] deg {deg} fit {e2:.2e} final {err:.2e}",
                  file=LOG)
            return ddl(mpc, k), deg
    print(f"{name} [{float(a):.5g},{float(b):.5g}] FAILED deg {deg} fit {e2:.2e}", file=LOG)
    return None, deg


def I(n, x):
    return mpmath.besseli(n, x)


def K(n, x):
    return mpmath.besselk(n, x)


# 1/Γ(1+μ) on [−1/2, 1/2].
cf, _ = best(lambda m: 1 / mpmath.gamma(1 + m), mpf(-0.5), mpf(0.5), lambda d: list(range(d + 1)),
             "rgam", maxdeg=30, mindeg=14)
arr("RGAM_DD", cf, "`1/Γ(1 + μ)` on `[−1/2, 1/2]`: `[c₀ hi, c₀ lo, c₁ hi, c₁ lo, c₂, …]`.")
cf = [cf[0] + cf[1], cf[2] + cf[3]] + cf[4:]
arr("RGAM", cf, "`1/Γ(1 + μ)` on `[−1/2, 1/2]`, a polynomial in `μ`.")

# I0, I1 on [0, 1] in s = x² (constant term fixed); e^(−x)·I_n(x) on pieces of [1, 7.75].
XI = mpf("7.75")
for n, name in [(0, "I0"), (1, "I1")]:
    if n == 0:
        f = lambda s: I(0, mpmath.sqrt(s))
        c0 = mpf(1)
        lead = "I₀(x) − 1"
    else:
        f = lambda s: I(1, mpmath.sqrt(s)) / mpmath.sqrt(s) if s > 0 else mpf(1) / 2
        c0 = mpf(1) / 2
        lead = "I₁(x)/x − 1/2"
    cf, d = best(f, mpf(0), mpf(1), lambda d: list(range(1, d + 1)), name + " small",
                 maxdeg=26, fixed={0: c0}, k=1)
    arr(name + "_SMALL", cf, f"`{lead}` on `[0, 1]`: `[c₁ hi, c₁ lo, c₂, …]` in `x²`.")
MCUTS = [mpf(1) + mpf(3) / 4 * k for k in range(10)]
for n, name in [(0, "I0"), (1, "I1")]:
    rows = []
    for a, b in zip(MCUTS, MCUTS[1:]):
        f = lambda x: I(n, x)
        m = (a + b) / 2  # about the midpoint: |u| ≤ half the piece, for Estrin's scheme
        cf, d = best(lambda u, m=m: f(m + u), a - m, b - m, lambda d: list(range(d + 1)),
                     name + " mid", maxdeg=26)
        rows.append([float(m)] + cf)
    arr2(name + "_MID", rows,
         f"`I_{n}(x)` on pieces of `[1, 7.75]` about their midpoints (`[x₀, c₀ hi, c₀ lo, c₁ hi, c₁ lo, c₂, …]`).")

# Large x: e^(−x)·√x·I_n(x) in t = 1/x, pieces [0, 1/50], [1/50, 1/7.75] (centered at the left).
CUTS = [mpf(0), mpf(1) / 500, mpf(1) / 50, mpf(1) / 20, 1 / XI]
for n, name in [(0, "I0"), (1, "I1")]:
    rows = []
    for a, b in zip(CUTS, CUTS[1:]):
        f = lambda t: (mpmath.exp(-1 / t) * mpmath.sqrt(1 / t) * I(n, 1 / t)) if t > 0 \
            else 1 / mpmath.sqrt(2 * PI)
        cf, d = best(lambda u, a=a: f(a + u), 0, b - a, lambda d: list(range(d + 1)),
                     name + " large", maxdeg=26)
        rows.append([float(a)] + cf)
    arr2(name + "_LARGE", rows,
         f"`e^(−x)·√x·I_{n}(x)` on pieces of `t = 1/x` (`[t₀, c₀ hi, c₀ lo, c₁ hi, c₁ lo, c₂, …]`, in `t − t₀`).")

# K0, K1 on (0, 1]: K0 = −ln x·I0(x) + R0(x²); K1 = ln x·I1(x) + 1/x + x·R1(x²).
def k0s(s):
    if s < mpf(10) ** -40:
        return mpmath.log(2) - mpmath.euler
    with mpmath.workprec(400):
        x = mpmath.sqrt(s)
        return +(K(0, x) + mpmath.log(x) * I(0, x))


f = k0s
cf, d = best(f, mpf(0), mpf(1), lambda d: list(range(d + 1)), "K0 small")
arr("K0_SMALL", cf, "`K₀(x) + ln x·I₀(x)` on `[0, 1]` as a polynomial in `x²`.")


def k1s(s):
    if s < mpf(10) ** -40:
        s = mpf(10) ** -40
    with mpmath.workprec(600):
        x = mpmath.sqrt(s)
        return +((K(1, x) - mpmath.log(x) * I(1, x) - 1 / x) / x)


cf, d = best(k1s, mpf(0), mpf(1), lambda d: list(range(d + 1)), "K1 small")
arr("K1_SMALL", cf, "`(K₁(x) − ln x·I₁(x) − 1/x)/x` on `[0, 1]` as a polynomial in `x²`.")

# K large: e^x·√x·K_n(x) in t = 1/x on pieces of [0, 1].
KCUTS = [mpf(0), mpf(1) / 40, mpf(1) / 12, mpf(1) / 6, mpf(1) / 3, mpf(1) / 2, mpf(1)]
for n, name in [(0, "K0"), (1, "K1")]:
    rows = []
    for a, b in zip(KCUTS, KCUTS[1:]):
        f = lambda t: (mpmath.exp(1 / t) * mpmath.sqrt(1 / t) * K(n, 1 / t)) if t > 0 \
            else mpmath.sqrt(PI / 2)
        cf, d = best(lambda u, a=a: f(a + u), 0, b - a, lambda d: list(range(d + 1)),
                     name + " large", maxdeg=26)
        rows.append([float(a)] + cf)
    arr2(name + "_LARGE", rows,
         f"`e^x·√x·K_{n}(x)` on pieces of `t = 1/x` (`[t₀, c₀ hi, c₀ lo, c₁ hi, c₁ lo, c₂, …]`, in `t − t₀`).")
w("/// The bounds of the pieces of `t = 1/x` of `I0_LARGE`/`I1_LARGE` and `K0_LARGE`/`K1_LARGE`,\n/// and of `x` of `I0_MID`/`I1_MID`.\n")
w("pub(super) const I_MID_CUTS: [f64; %d] = [%s];\n" % (len(MCUTS), ", ".join(repr(float(c)) for c in MCUTS)))
w("pub(super) const I_CUTS: [f64; %d] = [%s];\n" % (len(CUTS), ", ".join(repr(float(c)) for c in CUTS)))
w("pub(super) const K_CUTS: [f64; %d] = [%s];\n" % (len(KCUTS), ", ".join(repr(float(c)) for c in KCUTS)))
sys.stdout.write("".join(out))
