"""Generates `tables_f32.rs` beside this file: the tables of the `f32` forms of `J₀`, `J₁`, `Y₀` and `Y₁`.

`python3 gen_f32.py > tables_f32.rs && rustfmt --edition 2024 tables_f32.rs` (mpmath 1.3) gives the
file byte for byte.

On [0.5, 25): Chebyshev interpolants of degree D (mpmath at 40 digits) in x - c on pieces of
width 1/4 on [0.5, 1), 1/2 on [1, 2) and 1 on [2, 25) (the logarithmic singularity at 0 needs the
shorter pieces near it), on a piece with a zero z of Y(x)/(x - z) (times x - z from the
double-double z). On [0, 0.5): Y0 = (2/pi) ln(x) J0(x) + P0(x^2), Y1 = (2/pi) ln(x) J1(x) +
P1(x^2)/x, P0 and P1 entire, interpolants of degree DL in t = x^2 on [0, 1/4] about t = 1/8.
"""
import mpmath as mp, sys
mp.mp.dps = 40
D, DL = 14, 9
print("// Generated by src/math/special/bessel/gen_f32.py (mpmath): do not edit. Run there:")
print("// python3 gen_f32.py > tables_f32.rs && rustfmt --edition 2024 tables_f32.rs")
print("#![allow(clippy::excessive_precision, clippy::unreadable_literal)]")
print()


def emit_j(order, D=14):
    """`J0_F32`, `J1_F32`: degree 14 on the unit pieces of `[0, 25)` in `x − (i + 1/2)`, on a piece
    with a zero of `J(x)/(x − z)`."""
    J = (lambda x: mp.besselj(order, x))
    zeros = [mp.mpf(0)] if order == 1 else []
    zeros += [mp.besseljzero(order, k) for k in range(1, 10)]
    def fit(f, a, b, D):
        c, h = (a + b) / 2, (b - a) / 2
        N = D + 1
        xs = [mp.cos(mp.pi * (j + mp.mpf(1) / 2) / N) for j in range(N)]
        fs = [f(c + h * t) for t in xs]
        ch = [2 * mp.fsum(fs[j] * mp.cos(mp.pi * i * (j + mp.mpf(1) / 2) / N) for j in range(N)) / N for i in range(N)]
        ch[0] /= 2
        T = [[mp.mpf(1)], [mp.mpf(0), mp.mpf(1)]]
        for i in range(2, N):
            nx = [mp.mpf(0)] * (i + 1)
            for m_, v in enumerate(T[-1]): nx[m_ + 1] += 2 * v
            for m_, v in enumerate(T[-2]): nx[m_] -= v
            T.append(nx)
        mono = [mp.mpf(0)] * N
        for i in range(N):
            for m_, v in enumerate(T[i]): mono[m_] += ch[i] * v
        return [float(mono[i] / h**i) for i in range(N)]
    rows = []; worst = 0
    for i in range(25):
        a, b = mp.mpf(i), mp.mpf(i + 1)
        z = [z for z in zeros if a - mp.mpf('0.0') <= z < b]
        if z:
            z = z[0]
            f = lambda x, z=z: J(x) / (x - z) if abs(x - z) > mp.mpf(10)**-25 else mp.diff(J, z)
            zh = float(z); zl = float(z - zh); flag = 1.0
        else:
            f = J; zh = zl = 0.0; flag = 0.0
        cf = fit(f, a, b, D)
        c = float((a + b) / 2)
        err = 0
        for j in range(301):
            x = a + (b - a) * j / 300
            v = 0.0
            for k in reversed(cf): v = v * float(x - c) + k
            if flag: v = v * ((float(x) - zh) - zl)
            ex = J(mp.mpf(float(x)))
            if ex != 0: err = max(err, abs((v - ex) / ex))
        worst = max(worst, err)
        rows.append((cf, flag, zh, zl))
        print(i, flag, mp.nstr(err, 2), file=sys.stderr)
    print("worst", mp.nstr(worst, 3), file=sys.stderr)
    name = f"J{order}_F32"
    if True:
        o = sys.stdout
        o.write(f"/// `J{'₀₁'[order]}(x)` for the `f32` form on `0 ≤ x < 25`: Chebyshev interpolants of degree {D} in\n")
        o.write("/// `x − (i + 1/2)` on the pieces `[i, i + 1)` (mpmath at 40 digits), on a piece with a zero `z` of\n")
        o.write("/// `J(x)/(x − z)` (then times `x − z` from the double-double `z`, `x − zʰⁱ` exact there); relative\n")
        o.write(f"/// error at most {mp.nstr(worst, 2)} (an `f32` needs about `2⁻³⁴`). Each row: the coefficients, then\n")
        o.write("/// the flag of a zero (1 or 0) and the zero's two parts.\n")
        o.write(f"pub(super) const {name}: [[f64; {D + 4}]; 25] = [\n")
        for cf, flag, zh, zl in rows:
            o.write("    [\n" + "".join(f"        {v!r},\n" for v in cf + [flag, zh, zl]) + "    ],\n")
        o.write("];\n")

    o.write("\n")


def emit(order):
    Y = lambda x: mp.bessely(order, x)
    zeros = [mp.besselyzero(order, k) for k in range(1, 12)]


    def cheb_mono(f, a, b, D):
        c, h = (a + b) / 2, (b - a) / 2
        N = D + 1
        xs = [mp.cos(mp.pi * (j + mp.mpf(1) / 2) / N) for j in range(N)]
        fs = [f(c + h * t) for t in xs]
        ch = [2 * mp.fsum(fs[j] * mp.cos(mp.pi * i * (j + mp.mpf(1) / 2) / N) for j in range(N)) / N for i in range(N)]
        ch[0] /= 2
        T = [[mp.mpf(1)], [mp.mpf(0), mp.mpf(1)]]
        for i in range(2, N):
            nx = [mp.mpf(0)] * (i + 1)
            for m_, v in enumerate(T[-1]): nx[m_ + 1] += 2 * v
            for m_, v in enumerate(T[-2]): nx[m_] -= v
            T.append(nx)
        mono = [mp.mpf(0)] * N
        for i in range(N):
            for m_, v in enumerate(T[i]): mono[m_] += ch[i] * v
        return [float(mono[i] / h**i) for i in range(N)]


    def horner(cf, d):
        v = 0.0
        for k in reversed(cf): v = v * d + k
        return v


    pieces = [(mp.mpf(1) / 2 + mp.mpf(j) / 4, mp.mpf(1) / 2 + mp.mpf(j + 1) / 4) for j in range(2)]
    pieces += [(1 + mp.mpf(j) / 2, 1 + mp.mpf(j + 1) / 2) for j in range(2)]
    pieces += [(mp.mpf(i), mp.mpf(i + 1)) for i in range(2, 25)]
    rows = []
    worst = 0
    for a, b in pieces:
        z = [z for z in zeros if a <= z < b]
        if z:
            z = z[0]
            f = lambda x, z=z: Y(x) / (x - z) if abs(x - z) > mp.mpf(10) ** -25 else mp.diff(Y, z)
            zh = float(z); zl = float(z - zh); flag = 1.0
        else:
            f = Y; zh = zl = 0.0; flag = 0.0
        cf = cheb_mono(f, a, b, D)
        c = float((a + b) / 2)
        err = 0
        for j in range(401):
            x = float(a + (b - a) * j / 400)
            v = horner(cf, x - c)
            if flag: v = v * ((x - zh) - zl)
            ex = Y(mp.mpf(x))
            if ex != 0: err = max(err, abs((v - ex) / ex))
        worst = max(worst, err)
        rows.append((cf, flag, zh, zl, c))
        print(mp.nstr(a, 4), flag, mp.nstr(err, 2), file=sys.stderr)
    print("worst piece", mp.nstr(worst, 3), file=sys.stderr)

    # the logarithmic form on [0, 1/2)
    J = lambda x: mp.besselj(order, x)
    if order == 0:
        P = lambda t: (lambda x: Y(x) - 2 / mp.pi * mp.log(x) * J(x))(mp.sqrt(t)) if t > 0 else 2 / mp.pi * (mp.euler - mp.log(2))
    else:
        P = lambda t: (lambda x: x * (Y(x) - 2 / mp.pi * mp.log(x) * J(x)))(mp.sqrt(t)) if t > 0 else -2 / mp.pi
    lc = cheb_mono(P, mp.mpf(0), mp.mpf(1) / 4, DL)
    errl = 0
    for j in range(1, 2001):
        x = 0.5 * j / 2000
        t = x * x
        p = horner(lc, t - 0.125)
        pe = P(mp.mpf(t))
        errl = max(errl, abs((p - pe) / pe))
        # the whole form, J from mpmath (the J0/J1 tables are good to 2e-14)
        v = 2 / mp.pi * mp.log(x) * J(mp.mpf(x)) + (mp.mpf(p) if order == 0 else mp.mpf(p) / x)
        ex = Y(mp.mpf(x))
        worst = max(worst, abs((v - ex) / ex))
    print("log form: P rel", mp.nstr(errl, 3), "Y rel", mp.nstr(worst, 3), file=sys.stderr)

    sub = "₀₁"[order]
    name = f"Y{order}_F32"
    if True:
        o = sys.stdout
        o.write(f"/// `Y{sub}(x)` for the `f32` form on `1/2 ≤ x < 25`: Chebyshev interpolants of degree {D} in `x − c`\n")
        o.write("/// on the pieces of width 1/4 on `[1/2, 1)`, 1/2 on `[1, 2)` and 1 on `[2, 25)` (mpmath at 40\n")
        o.write("/// digits), on a piece with a zero `z` of `Y(x)/(x − z)` (then times `x − z` from the double-double\n")
        o.write(f"/// `z`); relative error at most {mp.nstr(worst, 2)}. Each row: the coefficients, the flag of a zero\n")
        o.write("/// (1 or 0), the zero's two parts and the centre `c`.\n")
        o.write(f"pub(super) const {name}: [[f64; {D + 5}]; {len(rows)}] = [\n")
        for cf, flag, zh, zl, c in rows:
            o.write("    [\n" + "".join(f"        {v!r},\n" for v in cf + [flag, zh, zl, c]) + "    ],\n")
        o.write("];\n\n")
        form = "(2/π) ln(x) J₀(x) + P(x²)" if order == 0 else "(2/π) ln(x) J₁(x) + P(x²)/x"
        o.write(f"/// `P` of `Y{sub}(x) = {form}` on `0 < x < 1/2` (`P` entire): the Chebyshev\n")
        o.write(f"/// interpolant of degree {DL} in `x² − 1/8` on `[0, 1/4]`, relative error {mp.nstr(errl, 2)}.\n")
        o.write(f"pub(super) const Y{order}_F32_LOG: [f64; {DL + 1}] = [\n" + "".join(f"    {v!r},\n" for v in lc) + "];\n")


emit_j(0)
emit_j(1)
emit(0)
print()
