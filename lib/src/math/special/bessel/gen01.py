"""Tables of J0, J1, Y0, Y1 (bessel/tables01.rs): expansions about the zeros up to x ~ 26, and the
modulus/phase fits beyond. Run here: python3 gen01.py > tables01.rs && rustfmt --edition 2024 tables01.rs"""

import sys

sys.dont_write_bytecode = True  # no __pycache__ beside the sources


import sys
import mpmath
from mpmath import mpf
from remez import fit

mp = mpmath.mp
mp.prec = 160
PI = mpmath.pi
TARGET = 2.0 ** -61
LOG = sys.stderr


def dd(v):
    h = float(v)
    return h, float(v - h)


def j(n, x):
    return mpmath.besselj(n, x)


def y(n, x):
    return mpmath.bessely(n, x)


def ddl(coef, k):
    """The first k coefficients as (hi, lo) pairs, then the rest as floats."""
    out = []
    for i, v in enumerate(coef):
        if i < k:
            h = float(v)
            out += [h, float(v - h)]
        else:
            out.append(float(v))
    return out


def zero_fit(f, df, z, lo, hi, maxdeg=22, name=""):
    """q(d) = f(z + d)/d on [lo − z, hi − z]: c0 = f'(z) exact (dd), then c1, c2 rounded in turn."""
    q = lambda d: f(z + d) / d if abs(d) > mpf(10) ** -30 else df(z)
    c0 = df(z)
    for deg in range(6, maxdeg + 1):
        cf, err, e2, mpc = fit(q, lo - z, hi - z, deg, center=0, grid=500,
                               basis=list(range(1, deg + 1)), fixed={0: c0}, exact=1,
                               want_mp=True)
        if e2 < TARGET:
            break
    print(f"{name} z={float(z):.6f} [{float(lo):.4f},{float(hi):.4f}] deg {deg} fit {e2:.2e} "
          f"final {err:.2e}", file=LOG)
    return deg, dd(c0), ddl(mpc, 1)


def plain_fit(f, lo, hi, deg_range, basis_fn, name, rel=True, center=0, fixed=None):
    for deg in deg_range:
        cf, err, e2, mpc = fit(f, lo, hi, deg, center=center, grid=500, basis=basis_fn(deg),
                               rel=rel, fixed=fixed, exact=1, want_mp=True)
        cf = ddl(mpc, 1)
        if e2 < TARGET:
            break
    print(f"{name} [{float(lo):.4f},{float(hi):.4f}] deg {deg} fit {e2:.2e} final {err:.2e}",
          file=LOG)
    return cf


out = []
w = out.append
w("// Generated by src/math/special/bessel/gen01.py (mpmath, Remez): do not edit. Run there:\n// python3 gen01.py > tables01.rs && rustfmt --edition 2024 tables01.rs\n")
w("#![allow(clippy::excessive_precision, clippy::unreadable_literal)]\n\n")


def arr(name, vals, doc):
    w(f"/// {doc}\n")
    w(f"pub(super) const {name}: [f64; {len(vals)}] = [\n")
    for v in vals:
        w(f"    {v!r},\n")
    w("];\n")


def arr2(name, rows, doc):
    n = len(rows[0])
    w(f"/// {doc}\n")
    w(f"pub(super) const {name}: [[f64; {n}]; {len(rows)}] = [\n")
    for r in rows:
        w("    [\n")
        for v in r:
            w(f"        {v!r},\n")
        w("    ],\n")
    w("];\n")


XMAX = 26.0  # the expansions about the zeros reach the last extremum below this


def outer_fit(f, a, b, name):
    """f(m + u) on [a, b], m the midpoint: c₀ as a double-double (Remez), then c₁, c₂, …"""
    m = (a + b) / 2
    for deg in range(6, 24):
        cf, err, e2, mpc = fit(lambda u: f(m + u), a - m, b - m, deg, center=0, grid=300,
                               exact=2, want_mp=True)
        if e2 < TARGET:
            break
    print(f"{name} outer [{float(a):.4f},{float(b):.4f}] deg {deg} fit {e2:.2e} final {err:.2e}",
          file=LOG)
    return deg, dd(m), ddl(mpc, 2)


def zero_tables(name, f, df, zeros, ext, start, nz):
    """Intervals [start, e1], [e1, e2], … each holding one zero, each in three pieces: about the
    zero (f(z + d) = d·q(d), z a double-double) on its middle third, and plain polynomials about
    the midpoints of the outer two. Rows `[centre hi, centre lo, c₀ hi, c₀ lo, c₁ hi, c₁ lo, c₂, …]`."""
    rows = []
    bounds = [start]
    pieces = []
    for k in range(nz):
        z = zeros[k]
        lo = bounds[-1]
        hi = [e for e in ext if e > z][0]
        w = (hi - lo) / 6
        a, b = z - w, z + w
        d0, mo, co = outer_fit(f, lo, a, name)
        rows.append(list(mo) + co)
        deg, c0, cs = zero_fit(f, df, z, a, b, name=name)
        rows.append(list(dd(z)) + [c0[0], c0[1]] + cs)
        d2, mo, co = outer_fit(f, b, hi, name)
        rows.append(list(mo) + co)
        pieces += [float(lo), float(a), float(b)]
        bounds.append(hi)
    n = max(len(r) for r in rows)
    rows = [r + [0.0] * (n - len(r)) for r in rows]
    U = name.upper()
    arr(f"{U}_B", [float(b) for b in bounds],
        f"The bounds of the intervals of `{name}` about its zeros.")
    arr(f"{U}_PB", pieces,
        f"The starts of the three pieces of each interval of `{name}` (left, about the zero, right).")
    arr2(f"{U}_C", rows,
         f"`{name}` on the pieces: `[centre hi, centre lo, c₀ hi, c₀ lo, c₁ hi, c₁ lo, c₂, …]` (about the zero "
         "the coefficients of `f(z + d)/d`).")
    return bounds


def lam_tables(name, n, z, lo, hi):
    """Y_n(x) = (2/π) ln(x/z) J_n(x) + (x − z) g(x) [/x for n = 1], fit of g about z."""
    if n == 0:
        G = lambda x: (y(0, x) - 2 / PI * mpmath.log(x / z) * j(0, x)) / (x - z)
    else:
        G = lambda x: (x * y(1, x) - 2 / PI * mpmath.log(x / z) * x * j(1, x)) / (x - z)
    def g(d):
        x = z + d
        if abs(d) < mpf(10) ** -25:
            x = z + mpf(10) ** -25
        if x < mpf(10) ** -30:
            x = mpf(10) ** -30
        return G(x)
    lo_ = max(lo, mpf(10) ** -30)
    for deg in range(6, 30):
        cf, err, e2, mpc = fit(g, lo_ - z, hi - z, deg, center=0, grid=500, exact=2,
                               want_mp=True)
        cf = ddl(mpc, 2)
        if e2 < TARGET:
            break
    print(f"{name} lam z={float(z):.6f} [{float(lo):.4f},{float(hi):.4f}] deg {deg} fit {e2:.2e} "
          f"final {err:.2e}", file=LOG)
    # cancellation check: max |(2/π)λ J| / |B|
    worst = 0
    for i in range(1, 200):
        x = lo_ + (hi - lo_) * i / 200
        d = x - z
        if abs(d) < 1e-6:
            continue
        lam = mpmath.log(x / z) / d
        t1 = 2 / PI * lam * (j(n, x) if n == 0 else j(1, x))
        B = (y(n, x) / d)
        worst = max(worst, abs(t1 / B))
    print(f"   cancellation |term|/|sum| <= {float(worst):.3f}", file=LOG)
    return cf


zj0 = [mpmath.besseljzero(0, k) for k in range(1, 13)]
zj1 = [mpmath.besseljzero(1, k) for k in range(1, 13)]
zy0 = [mpmath.besselyzero(0, k) for k in range(1, 13)]
zy1 = [mpmath.besselyzero(1, k) for k in range(1, 13)]
ej1d = [mpmath.besseljzero(1, k, derivative=1) for k in range(1, 13)]
ey1d = [mpmath.besselyzero(1, k, derivative=1) for k in range(1, 13)]

# J0: [0, 1.5] even polynomial; then the zeros below XMAX.
J0S = mpf("1.5")
cf = plain_fit(lambda x: j(0, x) if x > 0 else mpf(1), mpf(0), J0S, range(6, 20),
               lambda d: [2 * i for i in range(1, d + 1)], "j0 small", fixed={0: 1})
arr("J0_SMALL", cf, "`(J₀(x) − 1)/x²` on `[0, 1.5]` in `x²`: `[c₀ hi, c₀ lo, c₁, …]` (Remez).")
nz = len([z for z in zj0 if any(e > z for e in zj1) and [e for e in zj1 if e > z][0] < XMAX])
zero_tables("j0", lambda x: j(0, x), lambda x: -j(1, x), zj0, zj1, J0S, nz)

# J1: [0, first extremum] x·P(x²); then the zeros.
e1 = ej1d[0]
cf = plain_fit(lambda x: j(1, x) / x if x > 0 else mpf(1) / 2, mpf(0), e1, range(6, 20),
               lambda d: [2 * i for i in range(1, d + 1)], "j1 small", fixed={0: mpf(1) / 2})
arr("J1_SMALL", cf, "`(J₁(x)/x − 1/2)/x²` on `[0, 1.84]` in `x²`: `[c₀ hi, c₀ lo, c₁, …]` (Remez).")
nz = len([z for z in zj1 if any(e > z for e in ej1d) and [e for e in ej1d if e > z][0] < XMAX])
zero_tables("j1", lambda x: j(1, x), lambda x: j(0, x) - j(1, x) / x, zj1, ej1d, e1, nz)

# Y0: two λ-intervals [0, e1], [e1, e2]; then plain zero intervals.
ey0 = zy1  # extrema of Y0 = zeros of Y1
rows = []
zs = []
for k in range(2):
    lo = zy0[0] / 2 if k == 0 else ey0[k - 1]
    cf = lam_tables("y0", 0, zy0[k], lo, ey0[k])
    rows.append(cf)
    zs.append(dd(zy0[k]))
n = max(len(r) for r in rows)
arr2("Y0_LZ", [list(z) for z in zs], "The first two zeros of `Y₀` (double-double).")
arr2("Y0_LLN", [list(dd(mpmath.log(zy0[k]))) for k in range(2)], "`ln z` of those zeros.")
arr2("Y0_LC", [r + [0.0] * (n - len(r)) for r in rows],
     "`g` about the first two zeros of `Y₀ = (2/π) ln(x/z) J₀ + (x − z) g`.")
nz = len([z for z in zy0 if any(e > z for e in ey0) and [e for e in ey0 if e > z][0] < XMAX])
zero_tables("y0", lambda x: y(0, x), lambda x: -y(1, x), zy0[2:], ey0[1:], ey0[1], nz - 2)

# Y1.
rows = []
zs = []
for k in range(2):
    lo = zy1[0] / 2 if k == 0 else ey1d[k - 1]
    cf = lam_tables("y1", 1, zy1[k], lo, ey1d[k])
    rows.append(cf)
    zs.append(dd(zy1[k]))
n = max(len(r) for r in rows)
arr2("Y1_LZ", [list(z) for z in zs], "The first two zeros of `Y₁` (double-double).")
arr2("Y1_LLN", [list(dd(mpmath.log(zy1[k]))) for k in range(2)], "`ln z` of those zeros.")
arr2("Y1_LC", [r + [0.0] * (n - len(r)) for r in rows],
     "`e` about the first two zeros of `x·Y₁ = (2/π) ln(x/z) x·J₁ + (x − z) e`.")
nz = len([z for z in zy1 if any(e > z for e in ey1d) and [e for e in ey1d if e > z][0] < XMAX])
zero_tables("y1", lambda x: y(1, x), lambda x: y(0, x) - y(1, x) / x, zy1[2:], ey1d[1:],
            ey1d[1], nz - 2)


# Small x: Y0 = (2/π) ln x J0 + R0(x²), Y1 = (2/π)(ln x J1 − 1/x) + x R1(x²).
z0 = mpmath.besselyzero(0, 1); z1 = mpmath.besselyzero(1, 1)
e0 = mpmath.besselyzero(1, 1); e1 = mpmath.besselyzero(1, 1, derivative=1)
# R0(s) = Y0(x) − (2/π) ln(x) J0(x), s = x², on [0, (z0/2)²]
R0 = lambda x: y(0, x) - 2 / PI * mpmath.log(x) * j(0, x) if x > 0 else 2 / PI * (mpmath.euler - mpmath.log(2))
X0 = z0 / 2
for deg in range(4, 20):
    cf, err, e2, mpc = fit(lambda s: R0(mpmath.sqrt(s)), 0, X0 * X0, deg, center=0, grid=400,
                           exact=2, want_mp=True)
    cf = ddl(mpc, 2)
    if e2 < TARGET: break
print(f"R0 deg {deg} fit {e2:.2e} final {err:.2e} on x<{float(X0)}", file=LOG)
arr("Y0_R", cf, "`Y₀(x) − (2/π)·ln x·J₀(x)` as a polynomial in `x²`, `x ≤ z₁/2`.")
w(f"pub(super) const Y0_SMALL_X: f64 = {float(X0)!r};\n")
R1 = lambda x: (y(1, x) - 2 / PI * (mpmath.log(x) * j(1, x) - 1 / x)) / x
X1 = z1 / 2
def r1s(s):
    if s < mpf(10) ** -40:
        s = mpf(10) ** -40
    with mpmath.workprec(600):
        return +R1(mpmath.sqrt(s))
for deg in range(4, 20):
    cf, err, e2, mpc = fit(r1s, 0, X1 * X1, deg, center=0, grid=400, exact=2, want_mp=True)
    cf = ddl(mpc, 2)
    if e2 < TARGET: break
print(f"R1 deg {deg} fit {e2:.2e} final {err:.2e} on x<{float(X1)}", file=LOG)
arr("Y1_R", cf, "`(Y₁(x) − (2/π)·(ln x·J₁(x) − 1/x))/x` as a polynomial in `x²`, `x ≤ z₁/2`.")
w(f"pub(super) const Y1_SMALL_X: f64 = {float(X1)!r};\n")

# Modulus and phase for x ≥ X0.
X0 = mpf(24)


def MA(nu, x):
    jj = j(nu, x)
    yy = y(nu, x)
    M = mpmath.sqrt(jj * jj + yy * yy)
    th = mpmath.atan2(yy, jj)
    base = x - (2 * nu + 1) * PI / 4
    a = th - base
    a = a - 2 * PI * mpmath.nint(a / (2 * PI))
    return M, a


T = 1 / X0
for nu in (0, 1):
    fm = lambda t: MA(nu, 1 / t)[0] * mpmath.sqrt(1 / t) / mpmath.sqrt(2 / PI) - 1 if t > 0 else 0
    # (M√x/√(2/π) − 1)/t², polynomial in t²
    fm2 = lambda t: fm(t) / (t * t) if t > 0 else (4 * nu * nu - 1) / mpf(16) * (-1) * -1 / 1
    a0 = (4 * nu * nu - 1) / mpf(8)
    fa = lambda t: (MA(nu, 1 / t)[1] / t - a0) / (t * t) if t > 0 else None
    # limits at t = 0 from the series: M²·πx/2 = 1 + (μ−1)/(8x²)+…, so M√(πx/2) − 1 ~ (μ−1)/(16x²)
    mu = 4 * nu * nu
    fm2 = lambda t, mu=mu: fm(t) / (t * t) if t > mpf(10) ** -8 else (mu - 1) / 16
    a1 = (mu - 1) * (mu - 25) / 384
    fa2 = lambda t, mu=mu, a0=a0: (MA(nu, 1 / t)[1] / t - a0) / (t * t) if t > mpf(10) ** -8 else a1
    for deg in range(3, 12):
        cfm, errm, e2m = fit(fm2, 0, T, 2 * deg, center=0, grid=300,
                             basis=[2 * i for i in range(deg + 1)], rel=False)
        if errm * T * T < 2.0 ** -64:
            break
    print(f"M{nu} deg {deg} abs err {errm * float(T * T):.2e}", file=LOG)
    for deg in range(3, 12):
        cfa, erra, e2a = fit(fa2, 0, T, 2 * deg, center=0, grid=300,
                             basis=[2 * i for i in range(deg + 1)], rel=False)
        if erra * T ** 3 < 2.0 ** -70:
            break
    print(f"A{nu} deg {deg} abs err {erra * float(T ** 3):.2e}", file=LOG)
    arr(f"M{nu}", cfm, f"`(M_{nu}(x)·√(πx/2) − 1)/t²`, `t = 1/x ≤ 1/24`, as a polynomial in `t²`.")
    arr(f"A{nu}", cfa,
        f"`(α_{nu}(x)·x − {float(a0)})/t²`, `θ_{nu} = x − {2 * nu + 1}π/4 + α_{nu}`, in `t²`.")

sys.stdout.write("".join(out))
