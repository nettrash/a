/// `W₀(x)` for the `f32` form: on `1/1024 ≤ |x| ≤ 3` (above the branch point) `x·e^(−W)` with
/// `e^(−W)` from `W0_F32` in `p` (`1 + e·x` from the double-double `e`), good to `2⁻⁴⁹`, so that
/// the `f32` rounding is that of the true value but within `2⁻²⁵` ulp of a halfway point;
/// elsewhere `w0_f64`.
pub(crate) fn w0_f32(x: f64) -> f64 {
    if !(x <= 3.0 && x.abs() >= 1.0 / 1024.0) {
        return w0_f64(x);
    }
    let q = branch_q(x);
    if q < 0.0 {
        return below_branch(x);
    }
    let p = (2.0 * q).sqrt();
    let i = ((2.0 * p) as usize).min(8);
    x * super::bessel::kernels::estrin(p - (0.25 + 0.5 * i as f64), &W0_F32[i])
}

/// `W₋₁(x)` of an `f64`.
#[inline]
pub(crate) fn wm1_f64(x: f64) -> f64 {
    if x.is_nan() || x >= 0.0 {
        return if x == 0.0 {
            f64::NEG_INFINITY
        } else {
            f64::NAN
        };
    }
    let q = branch_q(x);
    if q < 0.0 {
        return below_branch(x);
    }
    let p = (2.0 * q).sqrt();
    if p <= 0.66 {
        let (p, pl) = branch_p(x);
        return if p <= 0.3 {
            full_dd(-p, -pl, &BRANCH_MID, BRANCH_MID_LO)
        } else {
            full_dd(0.48 - p, -pl, &BRANCH_WM1, BRANCH_WM1_LO)
        };
    }
    // s² = 2(u − 1), u = −ln(−x): from q = 1 + e·x, accurate, near the branch point, else from u.
    let (s, u) = if x <= -0.2 {
        let s2 = -2.0 * (-q).ln_1p();
        let s = s2.sqrt();
        if s <= 1.12 {
            // s as a double-double, from q as one: its rounding would cost 0.6 ulps of W
            let (sh, sl) = branch_s(x);
            return full_dd(sh - 0.86, sl, &FULL_S1, FULL_S1_LO);
        }
        (s, 0.5 * s2 + 1.0)
    } else {
        let u = -(-x).ln();
        ((2.0 * (u - 1.0)).sqrt(), u)
    };
    let w = if s <= 2.0 {
        horner(s - 1.55, &INIT_S2)
    } else if s <= 6.0 {
        horner(s - 4.0, &INIT_S3)
    } else if s <= 12.0 {
        horner(s - 9.0, &INIT_S4)
    } else {
        asymptotic(-u, u.ln())
    };
    if u <= 40.0 {
        halley(w, x)
    } else if u <= 700.0 {
        fritsch(w, (x / w).ln())
    } else {
        // x/w would underflow: ln(x/w) = ln(2¹²⁸ x / w) − 128 ln 2.
        let l = ((x * 2f64.powi(128)) / w).ln() - 128.0 * LN_2;
        fritsch(w, l)
    }
}

/// The principal branch `W₀(x)` of the Lambert W function, the `w ≥ −1` with `w e^w = x`, for
/// `x ≥ −1/e`.
///
/// # Examples
///
/// ```
/// use a::math::special::lambert_w0;
///
/// let w = lambert_w0(1.0f64); // the omega constant
/// assert!((w * w.exp() - 1.0).abs() < 1e-15);
/// assert_eq!(lambert_w0(-1.0f64 / core::f64::consts::E), -1.0);
/// ```
pub fn lambert_w0<T: Real>(x: T) -> T {
    super::via_f32(x, w0_f64, w0_f32)
}

/// The other real branch `W₋₁(x)`, the `w ≤ −1` with `w e^w = x`, for `−1/e ≤ x < 0`.
///
/// # Examples
///
/// ```
/// use a::math::special::lambert_wm1;
///
/// assert!((lambert_wm1(-0.1f64) + 3.577_152_063_957_297).abs() < 1e-14);
/// assert_eq!(lambert_wm1(0.0f64), f64::NEG_INFINITY);
/// ```
pub fn lambert_wm1<T: Real>(x: T) -> T {
    via(x, wm1_f64)
}
