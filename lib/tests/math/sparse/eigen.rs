#[test]
fn the_vectors_found_after_hundreds_of_restarts_are_still_orthonormal() {
    // Every restart replaces the basis by `V·Q`, and the rounding moves the lengths and angles of
    // its columns by an `ε` or so, a drift nothing undoes. The runs passed on what they locked
    // and the Ritz vectors they ended with as they were, and the vectors returned drifted with
    // them: here, after 300 to 1200 restarts, Lanczos's 60 to 87ε from length 1 and 17 to 41ε
    // from orthogonal, Arnoldi's (through a locked block) 58 and 90ε from length 1, on aarch64
    // (34 to 82ε, 10 to 43ε, 73 and 100ε on x86_64, where a vector of the large-basis test
    // above came back 150ε from length 1, past what that test allows). Measured with exact
    // inner products, they are now within 3ε of orthonormal on both; the bound is `16ε`.
    if cfg!(miri) {
        return;
    }
    fn lanczos_run<T: Num>() {
        let a = laplacian_1d::<T>(200);
        let opts = EigenOptions::new().with_basis(8).with_max_restarts(5000);
        let r = lanczos_with(&a, 4, LanczosWhich::SmallestAlgebraic, &opts).unwrap();
        assert_eq!(r.converged, 4);
        assert!(r.restarts >= 100, "{} restarts", r.restarts);
        let x: Vec<Vec<Complex<f64>>> = (0..4)
            .map(|j| r.vectors.column(j).iter().map(|&v| c64(v)).collect())
            .collect();
        let (length, angle) = deviations(&x);
        assert!(
            length <= 16.0 * T::EPS && angle <= 16.0 * T::EPS,
            "{:.1}ε from length 1, {:.1}ε from orthogonal",
            length / T::EPS,
            angle / T::EPS
        );
    }
    fn arnoldi_run<T: Num>() {
        let a = rotations::<T>(19, 300);
        let opts = EigenOptions::new().with_basis(10).with_max_restarts(5000);
        let r = arnoldi_with(&a, 6, ArnoldiWhich::LargestReal, &opts).unwrap();
        assert_eq!(r.converged, 6);
        assert!(r.restarts >= 100, "{} restarts", r.restarts);
        let x: Vec<Vec<Complex<f64>>> = (0..6)
            .map(|j| {
                r.vectors
                    .column(j)
                    .iter()
                    .map(|v| Complex::new(v.re.to_f64(), v.im.to_f64()))
                    .collect()
            })
            .collect();
        let (length, _) = deviations(&x);
        assert!(
            length <= 16.0 * T::EPS,
            "{:.1}ε from length 1",
            length / T::EPS
        );
    }
    each_type!(lanczos_run);
    arnoldi_run::<f32>();
    arnoldi_run::<f64>();
}

