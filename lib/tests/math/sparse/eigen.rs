/// The matrices of the generator script, from the same generator as `common.rs`.
///
/// `hermitian::<T>` is the script's `symmetric` for a real `T` and its `hermitian` for a complex
/// one: a diagonal of `3·unit()` and `per_row` pairs `(i, j), (j, i)` a row, conjugates.
fn hermitian<T: Num>(seed: u64, n: usize, per_row: usize) -> SparseMatrix<T> {
    let mut r = Rng(seed);
    let mut entries = Vec::new();
    for i in 0..n {
        entries.push((i, i, T::from_real(T::Real::from_f64(3.0 * r.unit()))));
        for _ in 0..per_row {
            let j = r.below(n);
            let x = element::<T>(&mut r);
            if j != i {
                entries.push((i, j, x));
                entries.push((j, i, x.conj()));
            }
        }
    }
    SparseMatrix::from_coo(n, n, &entries)
}

/// The script's `unsymmetric` for a real `T` and `complex_unsymmetric` for a complex one: a
/// diagonal of `3·unit()` (and `3·unit()·i`) and `per_row` more elements a row.
fn unsymmetric<T: Num>(seed: u64, n: usize, per_row: usize) -> SparseMatrix<T> {
    let mut r = Rng(seed);
    let mut entries = Vec::new();
    for i in 0..n {
        let re = 3.0 * r.unit();
        let d = if T::IS_COMPLEX {
            T::from_parts(T::Real::from_f64(re), T::Real::from_f64(3.0 * r.unit()))
        } else {
            T::from_real(T::Real::from_f64(re))
        };
        entries.push((i, i, d));
        for _ in 0..per_row {
            let j = r.below(n);
            entries.push((i, j, element::<T>(&mut r)));
        }
    }
    SparseMatrix::from_coo(n, n, &entries)
}

/// The script's `rotations`: blocks `a·[[1, −b], [b, 1]]` down the diagonal, eigenvalues
/// `a ± a·b·i`, and an upper triangle of random elements.
fn rotations<T: Num>(seed: u64, n: usize) -> SparseMatrix<T> {
    let mut r = Rng(seed);
    let mut entries = Vec::new();
    for p in 0..n / 2 {
        let a = 1.0 + 2.0 * (r.unit() + 1.0);
        let b = r.unit();
        let i = 2 * p;
        entries.push((i, i, T::real(a)));
        entries.push((i, i + 1, T::real(-a * b)));
        entries.push((i + 1, i, T::real(a * b)));
        entries.push((i + 1, i + 1, T::real(a)));
        for _ in 0..2 {
            let j = r.below(n);
            if j > i + 1 {
                entries.push((i, j, T::real(r.unit())));
            }
        }
    }
    SparseMatrix::from_coo(n, n, &entries)
}

/// A random element, its parts from `unit()`, the real part first: what the script draws.
fn element<T: Num>(r: &mut Rng) -> T {
    let re = r.unit();
    if T::IS_COMPLEX {
        T::from_parts(T::Real::from_f64(re), T::Real::from_f64(r.unit()))
    } else {
        T::from_real(T::Real::from_f64(re))
    }
}

/// The 1-D Laplacian of `n` points.
fn laplacian_1d<T: Num>(n: usize) -> SparseMatrix<T> {
    SparseMatrix::tridiagonal(
        &vec![T::real(-1.0); n - 1],
        &vec![T::real(2.0); n],
        &vec![T::real(-1.0); n - 1],
    )
}

/// The eigenvalues of the 1-D Laplacian of `n` points, ascending.
fn laplacian_1d_values(n: usize) -> Vec<f64> {
    (1..=n)
        .map(|j| 2.0 - 2.0 * (j as f64 * core::f64::consts::PI / (n + 1) as f64).cos())
        .collect()
}

/// The 2-D Laplacian of the five-point stencil on a grid of `nx × ny`.
fn laplacian_2d<T: Num>(nx: usize, ny: usize) -> SparseMatrix<T> {
    let n = nx * ny;
    let mut entries = Vec::with_capacity(5 * n);
    for y in 0..ny {
        for x in 0..nx {
            let p = x + y * nx;
            entries.push((p, p, T::real(4.0)));
            if x > 0 {
                entries.push((p, p - 1, T::real(-1.0)));
            }
            if x + 1 < nx {
                entries.push((p, p + 1, T::real(-1.0)));
            }
            if y > 0 {
                entries.push((p, p - nx, T::real(-1.0)));
            }
            if y + 1 < ny {
                entries.push((p, p + nx, T::real(-1.0)));
            }
        }
    }
    SparseMatrix::from_coo(n, n, &entries)
}

/// The eigenvalues of the 2-D Laplacian of `nx × ny`, ascending, every copy.
fn laplacian_2d_values(nx: usize, ny: usize) -> Vec<f64> {
    let pi = core::f64::consts::PI;
    let mut values = Vec::with_capacity(nx * ny);
    for i in 1..=nx {
        for j in 1..=ny {
            values.push(
                4.0 - 2.0 * (i as f64 * pi / (nx + 1) as f64).cos()
                    - 2.0 * (j as f64 * pi / (ny + 1) as f64).cos(),
            );
        }
    }
    values.sort_by(f64::total_cmp);
    values
}

/// The script's `clusters`: a diagonal of 200 with clusters at both ends and a triple 40.
fn clusters<T: Num>() -> SparseMatrix<T> {
    let mut d: Vec<f64> = (0..5).map(|j| 1.0 + j as f64 * 1e-3).collect();
    d.extend((0..3).map(|j| 5.0 + j as f64 * 1e-8));
    d.extend((0..184).map(|j| 10.0 + 0.05 * j as f64));
    d.extend([
        30.0,
        30.0 + 1e-6,
        30.0 + 2e-6,
        31.0,
        31.0 + 1e-4,
        40.0,
        40.0,
        40.0,
    ]);
    let d: Vec<T> = d.into_iter().map(T::real).collect();
    SparseMatrix::from_diagonal(&d)
}

/// `‖A‖₂` bounded above by `√(‖A‖₁·‖A‖∞)`, cheaply, for the scale of residuals.
fn norm_bound<T: Num>(a: &SparseMatrix<T>) -> f64 {
    let mut rows = vec![0.0f64; a.rows()];
    let mut cols = vec![0.0f64; a.cols()];
    for (i, row) in rows.iter_mut().enumerate() {
        for (j, x) in a.row(i) {
            let v = T::abs(x).to_f64();
            *row += v;
            cols[j] += v;
        }
    }
    let one = cols.iter().fold(0.0f64, |m, &x| m.max(x));
    let inf = rows.iter().fold(0.0f64, |m, &x| m.max(x));
    (one * inf).sqrt()
}

/// `A·x` in `f64` complex arithmetic, for a sparse `A` of any of the element types.
fn apply64<T: Num>(a: &SparseMatrix<T>, x: &[Complex<f64>]) -> Vec<Complex<f64>> {
    (0..a.rows())
        .map(|i| {
            a.row(i).fold(Complex::new(0.0, 0.0), |s, (j, v)| {
                let v = T::to_complex(v);
                s + Complex::new(v.re.to_f64(), v.im.to_f64()) * x[j]
            })
        })
        .collect()
}

/// An element as a complex `f64`.
fn c64<T: Num>(x: T) -> Complex<f64> {
    let z = T::to_complex(x);
    Complex::new(z.re.to_f64(), z.im.to_f64())
}

/// The 2-norm of a complex vector.
fn norm64(x: &[Complex<f64>]) -> f64 {
    x.iter().map(|z| z.norm_sqr()).sum::<f64>().sqrt()
}

/// `xᴴ·y` to about the rounding of its result alone: every product split into its rounded value
/// and its error by a fused multiply-add, and the sum compensated (Ogita, Rump and Oishi's
/// `Dot2`, SIAM J. Sci. Comput. 26, 2005). For vectors converted from the element type, whose
/// parts `f64` holds exactly, the deviations of a computed basis from orthonormality are then
/// measured without the `√n·ε` that a plain sum adds to them.
fn exact_dot(x: &[Complex<f64>], y: &[Complex<f64>]) -> Complex<f64> {
    let sum = |terms: &mut dyn Iterator<Item = (f64, f64)>| {
        let (mut s, mut c) = (0.0f64, 0.0f64);
        for (a, b) in terms {
            let p = a * b;
            let e = a.mul_add(b, -p);
            let t = s + p;
            let z = t - s;
            c += (s - (t - z)) + (p - z) + e;
            s = t;
        }
        s + c
    };
    let pairs = || x.iter().zip(y);
    let re = sum(&mut pairs().flat_map(|(u, v)| [(u.re, v.re), (u.im, v.im)]));
    let im = sum(&mut pairs().flat_map(|(u, v)| [(u.re, v.im), (-u.im, v.re)]));
    Complex::new(re, im)
}

/// The largest deviation from length 1 of the columns `x`, and the largest absolute inner
/// product of two of them, both by [`exact_dot`].
fn deviations(x: &[Vec<Complex<f64>>]) -> (f64, f64) {
    let (mut length, mut angle) = (0.0f64, 0.0f64);
    for (i, u) in x.iter().enumerate() {
        length = length.max((exact_dot(u, u).re.sqrt() - 1.0).abs());
        for v in &x[i + 1..] {
            angle = angle.max(exact_dot(u, v).abs());
        }
    }
    (length, angle)
}

/// The tolerance results of the type are compared with: `1e-9` for `f64`, `1e-4` for `f32`,
/// relative to the size of the matrix.
fn accuracy<T: Num>() -> f64 {
    if T::EPS < 1e-10 { 1e-9 } else { 1e-4 }
}

/// Checks everything a Lanczos result promises about itself, against `a`: as many values,
/// vectors and residuals as `converged`, the values ascending, the vectors orthonormal, and the
/// residual of every pair, recomputed here, below `bound·‖A‖` and equal to the one reported.
fn check_lanczos<T: Num>(a: &SparseMatrix<T>, r: &LanczosResult<T>, bound: f64) {
    let n = a.rows();
    let c = r.converged;
    assert_eq!(r.values.len(), c, "values against converged");
    assert_eq!(r.residuals.len(), c, "residuals against converged");
    assert_eq!(
        (r.vectors.rows(), r.vectors.cols()),
        (n, c),
        "the shape of the vectors"
    );
    let scale = norm_bound(a).max(f64::MIN_POSITIVE);
    for w in r.values.windows(2) {
        assert!(w[0] <= w[1], "the values are not ascending: {:?}", r.values);
    }
    let vectors: Vec<Vec<Complex<f64>>> = (0..c)
        .map(|j| r.vectors.column(j).iter().map(|&x| c64(x)).collect())
        .collect();
    for (i, x) in vectors.iter().enumerate() {
        let lambda = r.values[i].to_f64();
        let ax = apply64(a, x);
        let d: Vec<Complex<f64>> = ax.iter().zip(x).map(|(&y, &v)| y - v * lambda).collect();
        let residual = norm64(&d);
        assert!(
            residual <= bound * scale,
            "the residual {residual:e} of {lambda} is above {:e}",
            bound * scale
        );
        let reported = r.residuals[i].to_f64();
        assert!(
            (residual - reported).abs() <= 100.0 * T::EPS * scale,
            "the reported residual {reported:e} is not the true one {residual:e}"
        );
        for (j, y) in vectors.iter().enumerate() {
            let dot = x
                .iter()
                .zip(y)
                .fold(Complex::new(0.0, 0.0), |s, (u, v)| s + u.conj() * *v);
            let want = if i == j { 1.0 } else { 0.0 };
            assert!(
                (dot - Complex::new(want, 0.0)).abs() <= 100.0 * T::EPS * (n as f64).sqrt(),
                "the vectors {i} and {j} are not orthonormal: {dot:?}"
            );
        }
    }
}

/// Checks what an Arnoldi result promises about itself, against `a`: the counts, unit vectors,
/// conjugate pairs of a real matrix together and the residual of every pair, recomputed, below
/// `bound·‖A‖` and equal to the one reported.
fn check_arnoldi<T: Num>(a: &SparseMatrix<T>, r: &ArnoldiResult<T>, bound: f64) {
    let n = a.rows();
    let c = r.converged;
    assert_eq!(r.values.len(), c, "values against converged");
    assert_eq!(r.residuals.len(), c, "residuals against converged");
    assert_eq!(
        (r.vectors.rows(), r.vectors.cols()),
        (n, c),
        "the shape of the vectors"
    );
    let scale = norm_bound(a).max(f64::MIN_POSITIVE);
    for i in 0..c {
        let z = r.values[i];
        let lambda = Complex::new(z.re.to_f64(), z.im.to_f64());
        let x: Vec<Complex<f64>> = r
            .vectors
            .column(i)
            .iter()
            .map(|v| Complex::new(v.re.to_f64(), v.im.to_f64()))
            .collect();
        assert!(
            (norm64(&x) - 1.0).abs() < 100.0 * T::EPS,
            "vector {i} is not of length 1"
        );
        let ax = apply64(a, &x);
        let d: Vec<Complex<f64>> = ax.iter().zip(&x).map(|(&y, &v)| y - lambda * v).collect();
        let residual = norm64(&d);
        assert!(
            residual <= bound * scale,
            "the residual {residual:e} of {lambda:?} is above {:e}",
            bound * scale
        );
        let reported = r.residuals[i].to_f64();
        assert!(
            (residual - reported).abs() <= 100.0 * T::EPS * scale,
            "the reported residual {reported:e} is not the true one {residual:e}"
        );
        if !T::IS_COMPLEX && lambda.im != 0.0 {
            // The pair together: the conjugate next to it.
            let partner = if lambda.im > 0.0 { i + 1 } else { i - 1 };
            let w = r.values[partner];
            assert_eq!(
                (w.re.to_f64(), w.im.to_f64()),
                (lambda.re, -lambda.im),
                "{lambda:?} is not next to its conjugate"
            );
        }
    }
}

/// The real eigenvalues `got` against `want`, as multisets, within `tolerance` of the size
/// `scale`.
fn assert_same(got: &[f64], want: &[f64], tolerance: f64, scale: f64, what: &str) {
    assert_eq!(got.len(), want.len(), "{what}: {got:?} against {want:?}");
    let mut got = got.to_vec();
    got.sort_by(f64::total_cmp);
    let mut want = want.to_vec();
    want.sort_by(f64::total_cmp);
    for (g, w) in got.iter().zip(&want) {
        assert!(
            (g - w).abs() <= tolerance * scale,
            "{what}: {g} against {w} ({got:?} against {want:?})"
        );
    }
}

/// The complex eigenvalues `got` against `want` as multisets, within `tolerance` of the size
/// `scale`: each of `want` matched to a nearest one of `got` not matched before. `got` may hold
/// one more, the conjugate of one of its own, when a pair of a real matrix was completed.
fn assert_same_complex(
    got: &[Complex<f64>],
    want: &[Complex<f64>],
    tolerance: f64,
    scale: f64,
    what: &str,
) {
    assert!(
        got.len() == want.len() || got.len() == want.len() + 1,
        "{what}: {got:?} against {want:?}"
    );
    let mut used = vec![false; got.len()];
    for w in want {
        let best = (0..got.len())
            .filter(|&i| !used[i])
            .min_by(|&i, &j| (got[i] - *w).abs().total_cmp(&(got[j] - *w).abs()))
            .unwrap_or_else(|| panic!("{what}: nothing left for {w:?}"));
        assert!(
            (got[best] - *w).abs() <= tolerance * scale,
            "{what}: {w:?} not found ({got:?} against {want:?})"
        );
        used[best] = true;
    }
    if let Some(extra) = (0..got.len()).find(|&i| !used[i]) {
        let z = got[extra];
        assert!(
            z.im != 0.0 && got.iter().any(|&y| y == z.conj()),
            "{what}: {z:?} is extra and not the conjugate of another"
        );
    }
}

/// The values of a Lanczos result as `f64`.
fn values<T: Num>(r: &LanczosResult<T>) -> Vec<f64> {
    r.values.iter().map(|x| x.to_f64()).collect()
}

/// The values of an Arnoldi result as complex `f64`.
fn complex_values<T: Num>(r: &ArnoldiResult<T>) -> Vec<Complex<f64>> {
    r.values
        .iter()
        .map(|z| Complex::new(z.re.to_f64(), z.im.to_f64()))
        .collect()
}

/// Pairs `(re, im)` as complex numbers.
fn complex(values: &[(f64, f64)]) -> Vec<Complex<f64>> {
    values
        .iter()
        .map(|&(re, im)| Complex::new(re, im))
        .collect()
}

/// The `k` values of the ascending `all` that `which` asks for, as the methods define them.
fn lanczos_pick(all: &[f64], k: usize, which: LanczosWhich) -> Vec<f64> {
    let n = all.len();
    match which {
        LanczosWhich::LargestAlgebraic => all[n - k..].to_vec(),
        LanczosWhich::SmallestAlgebraic => all[..k].to_vec(),
        LanczosWhich::LargestMagnitude => {
            let mut v = all.to_vec();
            v.sort_by(|a, b| b.abs().total_cmp(&a.abs()));
            v.truncate(k);
            v
        }
        LanczosWhich::BothEnds => {
            let low = k / 2;
            let mut v = all[..low].to_vec();
            v.extend_from_slice(&all[n - (k - low)..]);
            v
        }
    }
}

/// The convergence tolerance the tests that compare across types use: `1e-12` for `f64`, the
/// default `ε` for `f32`.
fn options<T: Num>() -> EigenOptions<T> {
    let tolerance = if T::EPS < 1e-10 { 1e-12 } else { T::EPS };
    EigenOptions::new().with_tolerance(T::Real::from_f64(tolerance))
}

/// The bound on residuals relative to `‖A‖` for a result of the options of [`options`], or of
/// the default ones, whose tolerance is smaller: the `tol·‖A‖` the methods promise, with room for
/// the rounding of a factorisation of order `n`, `64·√n·ε·‖A‖`.
fn residual_bound<T: Num>(n: usize) -> f64 {
    let tolerance = if T::EPS < 1e-10 { 1e-12 } else { T::EPS };
    tolerance + 64.0 * (n.max(1) as f64).sqrt() * T::EPS
}

