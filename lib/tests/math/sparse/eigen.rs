/// The graph Laplacian of the hypercube `Q_d`, of order `2^d`: the eigenvalues `2j` with the
/// multiplicities `C(d, j)`, so `d + 1` distinct ones, and Krylov spaces that break down after
/// `d + 1` steps.
fn hypercube<T: Num>(d: usize) -> SparseMatrix<T> {
    let n = 1usize << d;
    let mut entries = Vec::with_capacity(n * (d + 1));
    for i in 0..n {
        entries.push((i, i, T::real(d as f64)));
        for b in 0..d {
            entries.push((i, i ^ (1 << b), T::real(-1.0)));
        }
    }
    SparseMatrix::from_coo(n, n, &entries)
}

/// The diagonal of 1, 2, 3 and 5 in turn, each 30 times: a Krylov space holds one copy of each.
fn four_values<T: Num>() -> SparseMatrix<T> {
    let d: Vec<T> = (0..120)
        .map(|i| T::real([1.0, 2.0, 3.0, 5.0][i % 4]))
        .collect();
    SparseMatrix::from_diagonal(&d)
}

/// The 3-D Laplacian of the seven-point stencil on a grid of `p³`.
fn laplacian_3d<T: Num>(p: usize) -> SparseMatrix<T> {
    let n = p * p * p;
    let at = |x: usize, y: usize, z: usize| x + p * (y + p * z);
    let mut entries = Vec::with_capacity(7 * n);
    for z in 0..p {
        for y in 0..p {
            for x in 0..p {
                let i = at(x, y, z);
                entries.push((i, i, T::real(6.0)));
                let mut neighbour = |j: usize| entries.push((i, j, T::real(-1.0)));
                if x > 0 {
                    neighbour(at(x - 1, y, z));
                }
                if x + 1 < p {
                    neighbour(at(x + 1, y, z));
                }
                if y > 0 {
                    neighbour(at(x, y - 1, z));
                }
                if y + 1 < p {
                    neighbour(at(x, y + 1, z));
                }
                if z > 0 {
                    neighbour(at(x, y, z - 1));
                }
                if z + 1 < p {
                    neighbour(at(x, y, z + 1));
                }
            }
        }
    }
    SparseMatrix::from_coo(n, n, &entries)
}

/// The eigenvalues of the 3-D Laplacian of `p³`, ascending, every copy:
/// `6 − 2·(cos iπ/(p+1) + cos jπ/(p+1) + cos kπ/(p+1))`.
fn laplacian_3d_values(p: usize) -> Vec<f64> {
    let c: Vec<f64> = (1..=p)
        .map(|i| (i as f64 * core::f64::consts::PI / (p + 1) as f64).cos())
        .collect();
    let mut values = Vec::with_capacity(p * p * p);
    for &a in &c {
        for &b in &c {
            for &d in &c {
                values.push(6.0 - 2.0 * (a + b + d));
            }
        }
    }
    values.sort_by(f64::total_cmp);
    values
}

/// `copies` copies of the square `block` down the diagonal.
fn copies<T: Num>(block: &SparseMatrix<T>, copies: usize) -> SparseMatrix<T> {
    let b = block.rows();
    let mut entries = Vec::new();
    for c in 0..copies {
        for i in 0..b {
            for (j, x) in block.row(i) {
                entries.push((i + c * b, j + c * b, x));
            }
        }
    }
    SparseMatrix::from_coo(b * copies, b * copies, &entries)
}

/// The real eigenvalues of an Arnoldi result, checking that they are real.
fn real_values<T: Num>(r: &ArnoldiResult<T>, scale: f64) -> Vec<f64> {
    complex_values(r)
        .iter()
        .map(|z| {
            assert!(z.im.abs() <= accuracy::<T>() * scale, "{z:?} is not real");
            z.re
        })
        .collect()
}

