#[test]
fn the_final_check_allows_for_the_accuracy_a_run_attains() {
    // Products 300ε off, as those of a larger or less accurate operator are: the residuals of
    // converged pairs cannot go below that, and the check after the iteration must not reject
    // them for it. (A fixed room of 64ε·‖A‖ rejected two of the six largest of the 2-D
    // Laplacian of 10⁵ unknowns at the default tolerance, whose residuals had reached 1.5·10⁻¹³.)
    fn run<T: Num>() {
        let n = size(200, 30);
        let a = laplacian_1d::<T>(n);
        let state = core::cell::Cell::new(0x2545_F491_4F6C_DD1Du64);
        let noisy = FnOperator::new(n, n, |x: &[T], y: &mut [T]| {
            a.mul_vec_into(x, y);
            let size = y
                .iter()
                .map(|&v| T::abs(v).to_f64().powi(2))
                .sum::<f64>()
                .sqrt();
            let scale = 300.0 * T::EPS * size / (n as f64).sqrt();
            for v in y.iter_mut() {
                let mut s = state.get();
                s ^= s << 13;
                s ^= s >> 7;
                s ^= s << 17;
                state.set(s);
                let u = (s >> 11) as f64 / (1u64 << 52) as f64 - 1.0;
                *v += T::real(u * scale);
            }
        });
        let opts = EigenOptions::new().with_max_restarts(5000);
        for which in [
            LanczosWhich::LargestAlgebraic,
            LanczosWhich::SmallestAlgebraic,
        ] {
            let r = lanczos_with(&noisy, 4, which, &opts).unwrap();
            assert_eq!(r.converged, 4, "{which:?}");
            // The residuals against the matrix itself, at the level of the noise; the reported
            // ones are against the noisy products.
            for (i, &lambda) in r.values.iter().enumerate() {
                let x: Vec<Complex<f64>> = r.vectors.column(i).iter().map(|&v| c64(v)).collect();
                let ax = apply64(&a, &x);
                let d: Vec<Complex<f64>> = ax
                    .iter()
                    .zip(&x)
                    .map(|(&y, &v)| y - v * lambda.to_f64())
                    .collect();
                assert!(norm64(&d) <= 2000.0 * T::EPS * 4.0, "{:e}", norm64(&d));
            }
            let exact = lanczos_pick(&laplacian_1d_values(n), 4, which);
            assert_same(&values(&r), &exact, 2000.0 * T::EPS, 4.0, "noisy");
        }
    }
    each_type!(run);
}

