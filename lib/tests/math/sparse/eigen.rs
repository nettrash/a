/// Checks pairs `(λ, x)` of a shift-and-invert result against `a` by the test their
/// convergence was judged by: `‖A·x − λ·x‖ ≤ tol·max(|λ|, ε^(2/3)·‖A‖) + 8·√n·ε·‖A‖`, `‖A‖` the
/// bound `√(‖A‖₁·‖A‖∞)` of the `SparseMatrix` drivers, the residual recomputed here in `f64`.
fn assert_shift_invert_test<T: Num>(
    a: &SparseMatrix<T>,
    pairs: &[(Complex<f64>, Vec<Complex<f64>>)],
    tolerance: f64,
    what: &str,
) {
    let n = a.rows();
    let size = norm_bound(a);
    for (l, x) in pairs {
        let ax = apply64(a, x);
        let d: Vec<Complex<f64>> = ax.iter().zip(x).map(|(&y, &v)| y - *l * v).collect();
        let residual = norm64(&d);
        let room = tolerance * l.abs().max(T::EPS.powf(2.0 / 3.0) * size)
            + 8.0 * (n as f64).sqrt() * T::EPS * size;
        assert!(
            residual <= room,
            "{what}: the residual {residual:e} of {l:?} is above {room:e}"
        );
    }
}

/// The pairs of a Lanczos result as complex `f64`, the values divided by `c`.
fn lanczos_pairs<T: Num>(r: &LanczosResult<T>, c: f64) -> Vec<(Complex<f64>, Vec<Complex<f64>>)> {
    (0..r.converged)
        .map(|i| {
            let x = r.vectors.column(i).iter().map(|&v| c64(v)).collect();
            (Complex::new(r.values[i].to_f64() / c, 0.0), x)
        })
        .collect()
}

/// The pairs of an Arnoldi result as complex `f64`, the values divided by `c`.
fn arnoldi_pairs<T: Num>(r: &ArnoldiResult<T>, c: f64) -> Vec<(Complex<f64>, Vec<Complex<f64>>)> {
    (0..r.converged)
        .map(|i| {
            let x = r
                .vectors
                .column(i)
                .iter()
                .map(|v| Complex::new(v.re.to_f64(), v.im.to_f64()))
                .collect();
            let z = r.values[i];
            (Complex::new(z.re.to_f64() / c, z.im.to_f64() / c), x)
        })
        .collect()
}

#[test]
fn shift_invert_through_the_sparse_lu_finds_the_same_for_a_scaled_matrix() {
    // `‖A‖` of the `SparseMatrix` drivers, `√(‖A‖₁·‖A‖∞)`, was formed as the square root of the
    // product of the two sums, which overflowed once `‖A‖` passed `10¹⁹` in `f32` and `10¹⁵⁴`
    // in `f64`, and underflowed to zero below `10⁻²⁵` and `10⁻¹⁶³`: the test that scales passed
    // every pair of the first factorisation as converged, with residuals up to 10¹⁰ times its
    // room, or none ever (review round 2, B1). Neither matrix needs a row interchange in
    // `A − σI`; the first factorisation of the diagonal, with a basis of `k + 1`, has not
    // converged.
    fn run<T: Num>() {
        let scales: [f64; 2] = if T::EPS < 1e-10 {
            [1e160, 1e-170]
        } else {
            [1e20, 1e-25]
        };
        let n = size(200, 30);
        let d: Vec<T> = (1..=n).map(|i| T::real(i as f64)).collect();
        let middle = (n / 2) as f64 + 0.37;
        let cases = [
            (SparseMatrix::from_diagonal(&d), middle, 6, Some(7)),
            (laplacian_1d::<T>(size(300, 40)), 0.0, 4, None),
        ];
        for (a, sigma, k, basis) in cases {
            let opts = match basis {
                Some(m) => EigenOptions::new().with_basis(m),
                None => EigenOptions::new(),
            };
            let tolerance = T::EPS;
            let scale = norm_bound(&a);
            let lanczos_one =
                lanczos_shift_invert_with(&a, T::Real::from_f64(sigma), k, &opts).unwrap();
            let arnoldi_one = arnoldi_shift_invert_with(&a, T::real(sigma), k, &opts).unwrap();
            assert_eq!(lanczos_one.converged, k, "σ = {sigma}");
            assert_eq!(arnoldi_one.converged, k, "σ = {sigma}");
            if basis.is_some() {
                assert!(lanczos_one.restarts > 0 && arnoldi_one.restarts > 0);
            }
            assert_shift_invert_test(&a, &lanczos_pairs(&lanczos_one, 1.0), tolerance, "c = 1");
            assert_shift_invert_test(&a, &arnoldi_pairs(&arnoldi_one, 1.0), tolerance, "c = 1");
            for c in scales {
                let b = a.map(|_, _, x| x * T::real(c));
                let what = format!("σ = {sigma}, c = {c:e}");
                let r =
                    lanczos_shift_invert_with(&b, T::Real::from_f64(sigma * c), k, &opts).unwrap();
                assert_eq!(r.converged, k, "Lanczos, {what}");
                let pairs = lanczos_pairs(&r, c);
                let got: Vec<f64> = pairs.iter().map(|p| p.0.re).collect();
                assert_same(&got, &values(&lanczos_one), accuracy::<T>(), scale, &what);
                assert_shift_invert_test(&a, &pairs, tolerance, &what);
                let r = arnoldi_shift_invert_with(&b, T::real(sigma * c), k, &opts).unwrap();
                assert_eq!(r.converged, k, "Arnoldi, {what}");
                let pairs = arnoldi_pairs(&r, c);
                let got: Vec<Complex<f64>> = pairs.iter().map(|p| p.0).collect();
                let want = complex_values(&arnoldi_one);
                assert_same_complex(&got, &want, accuracy::<T>(), scale, &what);
                assert_shift_invert_test(&a, &pairs, tolerance, &what);
            }
        }
    }
    each_type!(run);
}

#[test]
fn lanczos_shift_invert_of_a_complex_hermitian_matrix_converges_near_an_eigenvalue() {
    // The solves of a complex Hermitian `A − σI` near an eigenvalue are not Hermitian: the
    // rounding of the small pivot is complex, and the largest eigenvalue of the computed inverse
    // has an imaginary part of relative size about `ε·‖A‖/δ`. A Lanczos factorisation, whose `T`
    // is real, cannot hold that, and converged nothing in 300 restarts at targets `10⁻⁶·‖A‖`
    // from an eigenvalue and nearer, where the real case, the Arnoldi method on the same
    // inverse and ARPACK converge at once (review round 2, B2). The complex forms now carry an
    // Arnoldi factorisation and give the answer of a Hermitian matrix. The real types run the
    // same targets as a counterpart.
    fn run<T: Num>() {
        let n = 120;
        let a = hermitian::<T>(11, n, 3);
        let all: Vec<f64> = a
            .to_matrix()
            .hermitian_eigenvalues()
            .iter()
            .map(|x| x.to_f64())
            .collect();
        let norm2 = all.iter().fold(0.0f64, |m, x| m.max(x.abs()));
        let distances: &[f64] = if T::EPS < 1e-10 {
            &[1e-6, 1e-9]
        } else {
            &[1e-5]
        };
        for &e in distances {
            let sigma = all[60] + e * norm2;
            let what = format!("σ = λ₆₀ + {e:e}·‖A‖");
            let inverse = dense_inverse(&a, T::real(sigma));
            let r = lanczos_inverse_with(&a, &inverse, 3, &EigenOptions::new()).unwrap();
            assert_eq!(r.converged, 3, "{what}: {} restarts", r.restarts);
            check_lanczos(&a, &r, residual_bound::<T>(n));
            assert_shift_invert_test(&a, &lanczos_pairs(&r, 1.0), T::EPS, &what);
            let mut near = all.clone();
            near.sort_by(|x, y| (x - sigma).abs().total_cmp(&(y - sigma).abs()));
            assert_same(&values(&r), &near[..3], accuracy::<T>(), norm2, &what);
            // Through the `SparseMatrix` driver as well, where `SparseLu` solves `A − σI`: the
            // draft of `SparseLu` this was written against is wrong after a row interchange,
            // which this matrix needs, so this part runs only with a factorisation that solves.
            if sparse_lu_solves(&a, sigma) {
                let r = lanczos_shift_invert(&a, T::Real::from_f64(sigma), 3).unwrap();
                assert_eq!(r.converged, 3, "driver, {what}: {} restarts", r.restarts);
                check_lanczos(&a, &r, residual_bound::<T>(n));
                assert_same(&values(&r), &near[..3], accuracy::<T>(), norm2, &what);
            }
        }
    }
    if cfg!(miri) {
        return;
    }
    each_type!(run);
}

/// Whether `SparseLu` of `A − σI` solves a random right-hand side as a backward-stable solve
/// does.
fn sparse_lu_solves<T: Num>(a: &SparseMatrix<T>, sigma: f64) -> bool {
    let n = a.rows();
    let mut entries = Vec::with_capacity(a.nnz() + n);
    for i in 0..n {
        entries.extend(a.row(i).map(|(j, x)| (i, j, x)));
        entries.push((i, i, T::real(-sigma)));
    }
    let m = SparseMatrix::from_coo(n, n, &entries);
    let lu = SparseLu::new(&m);
    if lu.is_singular() {
        return false;
    }
    let mut r = Rng(5);
    let b: Vec<T> = (0..n).map(|_| T::random(&mut r)).collect();
    let Some(x) = lu.solve(&Matrix::from_column_major(n, 1, b.clone())) else {
        return false;
    };
    let x: Vec<Complex<f64>> = x.as_slice().iter().map(|&v| c64(v)).collect();
    let mx = apply64(&m, &x);
    let d: Vec<Complex<f64>> = mx.iter().zip(&b).map(|(&y, &v)| y - c64(v)).collect();
    norm64(&d) <= 1e3 * T::EPS * norm_bound(&m) * norm64(&x)
}

/// A complex Hermitian (for a real `T`, symmetric) tridiagonal matrix: the diagonal `1..=n`,
/// couplings `0.45·e^(iφ)` of phases that differ. For a target above its largest eigenvalue,
/// `A − σI` is negative definite with pivots larger than the couplings below them, so that
/// the factorisation makes no row interchange.
fn coupled_diagonal<T: Num>(n: usize) -> SparseMatrix<T> {
    let mut entries = Vec::new();
    for i in 0..n {
        entries.push((i, i, T::real((i + 1) as f64)));
        if i + 1 < n {
            let phase = 0.7 * i as f64 + 0.3;
            let (re, im) = (0.45 * phase.cos(), 0.45 * phase.sin());
            let x = if T::IS_COMPLEX {
                T::from_parts(T::Real::from_f64(re), T::Real::from_f64(im))
            } else {
                T::real(0.45)
            };
            entries.push((i + 1, i, x));
            entries.push((i, i + 1, x.conj()));
        }
    }
    SparseMatrix::from_coo(n, n, &entries)
}

