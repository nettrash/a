#[test]
fn lanczos_honours_the_size_of_the_basis() {
    // Three eigenvalues well above the other 147: even the smallest basis, `k + 1`, which
    // restarts with a single shift, converges. (On a clustered spectrum a basis that small
    // stagnates, as ARPACK's does: the 1-D Laplacian of 150 takes ARPACK 2498 restarts with 5
    // vectors and fails with 4.)
    let mut d: Vec<f64> = (0..147).map(|i| i as f64 / 147.0).collect();
    d.extend([10.0, 20.0, 30.0]);
    let a = SparseMatrix::from_diagonal(&d);
    // Too small a basis is raised to k + 1, too large a one lowered to n.
    for basis in [1, 4, 10, 40, 150, 1000] {
        let opts = EigenOptions::new().with_basis(basis);
        let r = lanczos_with(&a, 3, LanczosWhich::LargestAlgebraic, &opts).unwrap();
        assert_eq!(r.converged, 3, "basis {basis}");
        assert_same(&values(&r), &[10.0, 20.0, 30.0], 1e-12, 30.0, "basis");
        check_lanczos(&a, &r, 1e-12);
        if basis >= 150 {
            // The whole space: one factorisation, no restart.
            assert_eq!(r.restarts, 0);
        }
    }
}

