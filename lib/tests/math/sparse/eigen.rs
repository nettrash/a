#[test]
fn arnoldi_finds_the_same_for_a_scaled_operator() {
    // The first column of Francis's double-shift step was formed from products of elements of
    // `H`, which overflow past `‖A‖ ≈ 10¹⁹` in `f32` and `10¹⁵⁴` in `f64` and underflow at the
    // other end: real Arnoldi converged to nothing on `c·A` (review round 1, B2). Near the
    // underflow level complex Arnoldi failed too, through the reciprocal of a subnormal number
    // in its rotations, and the dense eigensolver lost pairs, until the small matrices were
    // scaled by a power of two before it. Down to where the rounding of a residual, `ε·‖A‖`, is
    // still a normal number, `c·A` gives what `A` gives; below, where the arithmetic keeps only
    // a few digits of such a residual, the most wanted eigenvalue still comes out.
    fn run<T: Num>() {
        let (scales, tiny): ([f64; 4], f64) = if T::EPS < 1e-10 {
            ([1e-280, 1e-150, 1e150, 1e280], 1e-300)
        } else {
            ([1e-30, 1e-20, 1e20, 1e30], 1e-35)
        };
        for (a, k, which) in [
            (rotations::<T>(19, 100), 4, ArnoldiWhich::LargestMagnitude),
            (rotations::<T>(19, 100), 4, ArnoldiWhich::LargestImaginary),
            (
                unsymmetric::<T>(13, 80, 3),
                4,
                ArnoldiWhich::LargestMagnitude,
            ),
            (unsymmetric::<T>(13, 80, 3), 4, ArnoldiWhich::LargestReal),
            (
                unsymmetric::<T>(13, 80, 3),
                4,
                ArnoldiWhich::LargestImaginary,
            ),
        ] {
            let reference = arnoldi(&a, k, which).unwrap();
            assert!(reference.converged >= k, "{which:?}");
            let want = complex_values(&reference);
            let size = norm_bound(&a);
            for scale in scales {
                let b = a.map(|_, _, x| x * T::real(scale));
                let r = arnoldi(&b, k, which).unwrap();
                assert!(r.converged >= k, "{which:?} at {scale:e}: {}", r.converged);
                let got: Vec<Complex<f64>> =
                    complex_values(&r).iter().map(|z| *z / scale).collect();
                assert_same_complex(&got, &want, accuracy::<T>(), size, "scaled");
                for &x in &r.residuals {
                    let relative = x.to_f64() / scale;
                    assert!(relative <= residual_bound::<T>(80) * size, "{relative:e}");
                }
            }
            let b = a.map(|_, _, x| x * T::real(tiny));
            let r = arnoldi(&b, k, which).unwrap();
            assert!(r.converged >= 1, "{which:?} at {tiny:e}");
            let first = Complex::new(r.values[0].re.to_f64(), r.values[0].im.to_f64()) / tiny;
            let near = want
                .iter()
                .fold(f64::INFINITY, |m, w| m.min((first - *w).abs()));
            assert!(near <= accuracy::<T>() * size, "{first:?} at {tiny:e}");
        }
    }
    if cfg!(miri) {
        return;
    }
    each_type!(run);
}

