#[test]
fn shift_invert_near_an_eigenvalue_reports_only_eigenpairs_of_the_matrix() {
    // Targets 1 ulp, 10⁻⁹ and 10⁻⁶ from the eigenvalue 7 of the diagonal 1..60. The test of
    // convergence on `(A − σI)⁻¹` had a floor of `ε·‖(A − σI)⁻¹‖ = ε/δ`, which let the other
    // pairs pass with residuals with `A` of up to `10¹¹·tol·‖A‖` (review round 1, B4): 5.999946
    // was reported for 6. Now every pair is judged by its residual with `A`, and a converged
    // value `1/δ` is locked before it can spoil the others. ARPACK finds 6, 7 and 8 at every
    // such target, and so must these, through both drivers and both inverse forms; a target
    // that rounds to 7 in the element type gives `None`.
    fn run<T: Num>() {
        let n = 60;
        let d: Vec<T> = (1..=n).map(|i| T::real(i as f64)).collect();
        let a = SparseMatrix::from_diagonal(&d);
        let scale = norm_bound(&a);
        // `tol·max(|λ|, ε^(2/3)·‖A‖)` with the default `tol = ε`, and room for rounding.
        let bound = 4.0 * T::EPS * 8.0 / scale + 8.0 * (n as f64).sqrt() * T::EPS;
        for offset in [4.0 * T::EPS, 1e-9, 1e-6] {
            let sigma = T::Real::from_f64(7.0 + offset);
            if sigma.to_f64() == 7.0 {
                assert!(lanczos_shift_invert(&a, sigma, 3).is_none());
                assert!(arnoldi_shift_invert(&a, T::from_real(sigma), 3).is_none());
                continue;
            }
            let inverse = dense_inverse(&a, T::from_real(sigma));
            let what = format!("σ = 7 + {offset:e}");
            let results = [
                lanczos_shift_invert(&a, sigma, 3).unwrap(),
                lanczos_inverse_with(&a, &inverse, 3, &EigenOptions::new()).unwrap(),
            ];
            for r in &results {
                assert_eq!(r.converged, 3, "{what}: {:?}", values(r));
                check_lanczos(&a, r, bound);
                assert_same(&values(r), &[6.0, 7.0, 8.0], accuracy::<T>(), 8.0, &what);
            }
            let results = [
                arnoldi_shift_invert(&a, T::from_real(sigma), 3).unwrap(),
                arnoldi_inverse_with(&a, &inverse, 3, &EigenOptions::new()).unwrap(),
            ];
            for r in &results {
                assert_eq!(r.converged, 3, "{what}");
                check_arnoldi(&a, r, bound);
                let got = real_values(r, 8.0);
                assert_same(&got, &[6.0, 7.0, 8.0], accuracy::<T>(), 8.0, &what);
            }
        }
    }
    each_type!(run);
}

/// Rotation blocks `a·[[1, −b], [b, 1]]` and real diagonal elements, in a random order down the
/// diagonal, with some elements above it: a real matrix whose real eigenvalues and conjugate
/// pairs are mixed.
fn mixed<T: Num>(seed: u64, n: usize) -> SparseMatrix<T> {
    let mut r = Rng(seed);
    let mut entries = Vec::new();
    let mut i = 0;
    while i < n {
        if i + 1 < n && r.unit() > 0.0 {
            let (a, b) = (3.0 * r.unit(), r.unit());
            entries.push((i, i, T::real(a)));
            entries.push((i, i + 1, T::real(-b)));
            entries.push((i + 1, i, T::real(b)));
            entries.push((i + 1, i + 1, T::real(a)));
            i += 2;
        } else {
            entries.push((i, i, T::real(3.0 * r.unit())));
            i += 1;
        }
    }
    for row in 0..n {
        let j = r.below(n);
        if j > row {
            entries.push((row, j, T::real(0.3 * r.unit())));
        }
    }
    SparseMatrix::from_coo(n, n, &entries)
}

