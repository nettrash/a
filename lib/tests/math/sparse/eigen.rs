/// `(A − σI)⁻¹` by the dense LU decomposition, as an operator.
fn dense_inverse<T: Num>(a: &SparseMatrix<T>, sigma: T) -> impl LinearOperator<T> {
    let n = a.rows();
    let shifted = Matrix::from_fn(n, n, |i, j| {
        let x = a[(i, j)];
        if i == j { x - sigma } else { x }
    });
    let lu = shifted.lu();
    FnOperator::new(n, n, move |x: &[T], y: &mut [T]| {
        let b = Matrix::from_column_major(n, 1, x.to_vec());
        y.copy_from_slice(lu.solve(&b).unwrap().as_slice());
    })
}

