/// A matrix of the element type with the elements of the real `unsymmetric::<f64>(13, 150, 3)`
/// of the generator script, and its real eigenvalue nearest 1.448927, in `f64`.
fn real_unsymmetric<T: Num>() -> (SparseMatrix<T>, f64) {
    let base = unsymmetric::<f64>(13, 150, 3);
    let n = base.rows();
    let entries: Vec<(usize, usize, T)> = (0..n)
        .flat_map(|i| base.row(i).map(move |(j, x)| (i, j, T::real(x))))
        .collect();
    let lambda = base
        .to_matrix()
        .eigen()
        .values()
        .iter()
        .filter(|z| z.im == 0.0)
        .map(|z| z.re)
        .fold(f64::NAN, |best, x| {
            if best.is_nan() || (x - 1.448927).abs() < (best - 1.448927).abs() {
                x
            } else {
                best
            }
        });
    (SparseMatrix::from_coo(n, n, &entries), lambda)
}

#[test]
fn shift_invert_near_an_eigenvalue_of_a_matrix_that_is_not_normal_needs_a_looser_tolerance() {
    // A vector orthogonal to the eigenvector nearest `σ` still has a component along its left
    // eigenvector, so the solves give it one `1/δ` times larger along the nearest eigenvector,
    // whose rounding leaves the other pairs with residuals of about `ε·‖A‖·|λⱼ − σ|/δ`: above
    // the room of the test at the default tolerance once `δ` is below about `10⁻³·‖A‖`, in
    // every precision (review round 2, B3; ARPACK's are of the same size). With the defaults
    // the nearest pair comes back, first and right, every pair reported passes with `A`, and
    // the call no longer spends its whole budget on the others; with the tolerance
    // `10·ε·‖A‖/δ` the three nearest come back.
    fn run<T: Num>() {
        let (a, lambda) = real_unsymmetric::<T>();
        let n = a.rows();
        let scale = norm_bound(&a);
        let target = Complex::new(lambda, 0.0);
        let mut dense: Vec<Complex<f64>> = unsymmetric::<f64>(13, 150, 3)
            .to_matrix()
            .eigen()
            .values()
            .to_vec();
        for e in [1e-4, 1e-6] {
            let sigma = T::real(lambda + e * scale);
            let s = c64(sigma);
            dense.sort_by(|x, y| (*x - s).abs().total_cmp(&(*y - s).abs()));
            let delta = (dense[0] - s).abs();
            let what = format!("σ = λ + {e:e}·‖A‖");
            let inverse = dense_inverse(&a, sigma);
            let r = arnoldi_inverse_with(&a, &inverse, 3, &EigenOptions::new()).unwrap();
            assert!(r.converged >= 1, "{what}: nothing");
            assert!(r.restarts < 300, "{what}: the whole budget");
            check_arnoldi(&a, &r, residual_bound::<T>(n));
            let first = complex_values(&r)[0];
            assert!(
                (first - target).abs() <= accuracy::<T>() * scale,
                "{what}: {first:?}"
            );
            let tolerance = 10.0 * T::EPS * scale / delta;
            if tolerance < 0.1 {
                let opts = EigenOptions::new().with_tolerance(T::Real::from_f64(tolerance));
                let r = arnoldi_inverse_with(&a, &inverse, 3, &opts).unwrap();
                assert!(
                    r.converged >= 3,
                    "{what}, tol {tolerance:e}: {}",
                    r.converged
                );
                let work = n.max(20 * (r.restarts + 1));
                let room = 4.0 * tolerance + 64.0 * (work as f64).sqrt() * T::EPS;
                check_arnoldi(&a, &r, room);
                let got = complex_values(&r);
                let near = accuracy::<T>().max(10.0 * tolerance);
                assert_same_complex(&got, &dense[..got.len()], near, scale, &what);
            }
        }
    }
    if cfg!(miri) {
        return;
    }
    each_type!(run);
}

#[test]
fn shift_invert_near_an_eigenvalue_keeps_its_basis_orthonormal_and_the_nearest_pair() {
    // Near an eigenvalue of a matrix that is not normal the runs went on restarting about the
    // pairs other than the nearest, which converge on the inverse but not with `A`: blocks that
    // split off at the level of rounding were locked without the test with `A`, the residual of
    // a restart shrank into subnormal numbers and so did couplings of `H`, whose rotations were
    // then not orthogonal; the basis lost its orthonormality, `H` grew to 10⁴³, and calls with
    // `k = 3` returned nothing, not even the nearest pair, which `k = 1` found at once (review
    // round 2). Targets that round onto the eigenvalue in the element type are skipped: their
    // `A − σI` is singular in it.
    fn run<T: Num>() {
        for seed in 1..=size(20, 2) as u64 {
            let n = 80;
            let a = unsymmetric::<T>(seed * 104_729, n, 3);
            let scale = norm_bound(&a);
            let all: Vec<Complex<f64>> = a
                .to_matrix()
                .eigen()
                .values()
                .iter()
                .map(|z| Complex::new(z.re.to_f64(), z.im.to_f64()))
                .collect();
            let candidates: Vec<Complex<f64>> = if T::IS_COMPLEX {
                all.clone()
            } else {
                all.iter().copied().filter(|z| z.im == 0.0).collect()
            };
            if candidates.is_empty() {
                continue;
            }
            let z = candidates[seed as usize % candidates.len()];
            for e in [1e-6, 1e-8] {
                let sigma = if T::IS_COMPLEX {
                    T::from_parts(
                        T::Real::from_f64(z.re + 0.6 * e * scale),
                        T::Real::from_f64(z.im + 0.8 * e * scale),
                    )
                } else {
                    T::real(z.re + e * scale)
                };
                let s = c64(sigma);
                let mut near = all.clone();
                near.sort_by(|x, y| (*x - s).abs().total_cmp(&(*y - s).abs()));
                if (near[0] - s).abs() < 1e3 * T::EPS * scale {
                    continue;
                }
                let what = format!("seed {seed}, σ at {e:e}·‖A‖");
                let inverse = dense_inverse(&a, sigma);
                let r = arnoldi_inverse_with(&a, &inverse, 3, &EigenOptions::new()).unwrap();
                assert!(
                    r.converged >= 1,
                    "{what}: nothing after {} restarts",
                    r.restarts
                );
                check_arnoldi(&a, &r, residual_bound::<T>(n));
                let first = complex_values(&r)[0];
                assert!(
                    (first - near[0]).abs() <= accuracy::<T>() * scale,
                    "{what}: {first:?} is not the nearest {:?}",
                    near[0]
                );
            }
        }
    }
    if cfg!(miri) {
        return;
    }
    each_type!(run);
}
