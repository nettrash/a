#!/usr/bin/env python3
"""Reference outputs of LLL with deep insertions for tests/math/lattice/deep.rs: deep_reference.txt.

For each case a knapsack basis is generated exactly as the tests generate it (SplitMix64, as `Rng`
and `knapsack` in common.rs) and reduced by NTL 11 (`LLL_FP(B, 0.99, deep)` through gen_deep_ntl.cpp)
with deep = 0 (plain LLL), deep = 5 and deep = n (insertions anywhere); a line is written:

    n bits seed ntl_lll ntl_deep5 ntl_deep_all

with the squared norm of the first nonzero row of each result.

Usage: python3 gen_deep_reference.py > deep_reference.txt
       (gen_deep_ntl must be built first, see gen_deep_ntl.cpp; set NTL_DEEP to its path.)
"""
import os
import subprocess

M = (1 << 64) - 1


class Rng:
    def __init__(self, seed):
        self.s = seed & M

    def next(self):
        self.s = (self.s + 0x9E3779B97F4A7C15) & M
        z = self.s
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & M
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & M
        return z ^ (z >> 31)

    def number(self, bits):
        x, left = 0, bits
        while left > 0:
            take = min(left, 64)
            w = self.next() if take == 64 else self.next() >> (64 - take)
            x = (x << take) + w
            left -= take
        return -x if self.next() & 1 else x


def knapsack(rng, n, bits):
    # Matrix::from_fn calls f a column at a time; only column 0 draws numbers.
    col = [abs(rng.number(bits)) for _ in range(n)]
    return [[col[i]] + [int(i + 1 == j) for j in range(1, n + 1)] for i in range(n)]


def text(b):
    return "[" + "\n".join("[" + " ".join(map(str, r)) + "]" for r in b) + "]\n"


ntl = os.environ.get("NTL_DEEP", "./gen_deep_ntl")
print("# n bits seed ntl_lll ntl_deep5 ntl_deep_all -- generated by gen_deep_reference.py")
seed = 500
for n in (12, 16, 20, 24):
    for bits in (2 * n, 3 * n, 5 * n):
        for _ in range(2):
            seed += 1
            t = text(knapsack(Rng(seed), n, bits))
            out = [subprocess.run([ntl, "0.99", str(d)], input=t, capture_output=True, text=True,
                                  check=True).stdout.strip() for d in (0, 5, n)]
            print(n, bits, seed, *out)
