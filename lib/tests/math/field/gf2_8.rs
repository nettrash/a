#[test]
fn the_aes_sbox_is_the_inverse_then_the_affine_map_as_fips_197_tabulates_it() {
    for b in 0..=255u8 {
        assert_eq!(
            Gf2_8::new(b).aes_sbox().to_byte(),
            SBOX[b as usize],
            "{b:#04x}"
        );
        assert_eq!(
            Gf2_8::new(b).aes_inverse_sbox().to_byte(),
            INVSBOX[b as usize],
            "{b:#04x}"
        );
    }
}

#[test]
fn the_examples_of_fips_197() {
    let e = Gf2_8::new;
    // 4.1: {57} + {83} = {d4}.
    assert_eq!(e(0x57) + e(0x83), e(0xd4));
    assert_eq!(e(0x57) - e(0x83), e(0xd4));
    // 4.2: {57}·{83} = {c1}; 4.2.1: {57}·{13} = {fe} by xtime.
    assert_eq!(e(0x57) * e(0x83), e(0xc1));
    assert_eq!(e(0x57) * e(0x13), e(0xfe));
    let x = [0x57, 0xae, 0x47, 0x8e, 0x07];
    let mut t = e(0x57);
    for &want in &x[1..] {
        t = t.xtime();
        assert_eq!(t, e(want));
    }
    // 5.1.1: SBOX({53}) = {ed}, by the inverse {ca}.
    assert_eq!(e(0x53).inverse(), Some(e(0xca)));
    assert_eq!(e(0x53).aes_sbox(), e(0xed));
}

#[test]
fn every_product_and_quotient_agrees_with_the_binary_field() {
    let f = BinaryField::new(&[8, 4, 3, 1, 0]);
    let step = if cfg!(miri) { 37 } else { 1 };
    for a in (0..=255u8).step_by(step) {
        let fa = f.element(&[u64::from(a)]);
        for b in 0..=255u8 {
            let fb = f.element(&[u64::from(b)]);
            let p = Gf2_8::new(a) * Gf2_8::new(b);
            assert_eq!(
                u64::from(p.to_byte()),
                (&fa * &fb).words()[0],
                "{a:#04x}·{b:#04x}"
            );
            if b != 0 {
                let q = Gf2_8::new(a) / Gf2_8::new(b);
                assert_eq!(u64::from(q.to_byte()), (&fa / &fb).words()[0]);
                assert_eq!(q * Gf2_8::new(b), Gf2_8::new(a));
            }
        }
    }
}

#[test]
fn inverses_and_powers() {
    let f = BinaryField::new(&[8, 4, 3, 1, 0]);
    assert_eq!(Gf2_8::ZERO.inverse(), None);
    for a in (1..=255u8).step_by(if cfg!(miri) { 31 } else { 1 }) {
        let g = Gf2_8::new(a);
        let inv = g.inverse().unwrap();
        assert_eq!(g * inv, Gf2_8::ONE);
        assert_eq!(
            u64::from(inv.to_byte()),
            f.element(&[u64::from(a)]).inverse().unwrap().words()[0]
        );
        assert_eq!(g.pow(255), Gf2_8::ONE);
        assert_eq!(g.pow(254), inv);
        for e in [0u64, 1, 2, 3, 7, 254, 256, 1000, u64::MAX] {
            assert_eq!(
                u64::from(g.pow(e).to_byte()),
                f.element(&[u64::from(a)]).pow_u64(e).words()[0],
                "{a:#04x}^{e}"
            );
        }
    }
    assert_eq!(Gf2_8::ZERO.pow(0), Gf2_8::ONE);
    assert_eq!(Gf2_8::ZERO.pow(5), Gf2_8::ZERO);
    // {03} generates the multiplicative group: its powers are the 255 nonzero bytes.
    let mut seen = [false; 256];
    for e in 0..255 {
        seen[Gf2_8::new(3).pow(e).to_byte() as usize] = true;
    }
    assert_eq!(seen.iter().filter(|&&s| s).count(), 255);
}

#[test]
fn bytes_operators_and_formatting() {
    let a = Gf2_8::from(0x57u8);
    assert_eq!(u8::from(a), 0x57);
    assert_eq!(-a, a);
    let mut b = a;
    b += Gf2_8::ONE;
    assert_eq!(b, Gf2_8::new(0x56));
    b -= Gf2_8::ONE;
    b *= Gf2_8::new(0x83);
    assert_eq!(b, Gf2_8::new(0xc1));
    b /= Gf2_8::new(0x83);
    assert_eq!(b, a);
    assert_eq!(Gf2_8::default(), Gf2_8::ZERO);
    assert_eq!(format!("{a:?}"), "Gf2_8({57})");
}

