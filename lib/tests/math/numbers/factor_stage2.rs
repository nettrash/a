/// `f` is `p` in the byte order of `n`.
fn is(f: &Option<Number>, p: &str, n: &Number) {
    let f = f.as_ref().unwrap_or_else(|| panic!("a factor of {n}"));
    assert!(f.byte_order() == n.byte_order(), "the byte order of n");
    assert_eq!(f.to_string(), p, "the factor of {n}");
}

/// Checks that `f` is a factor of `n` other than 1 and `|n|`, in the byte order of `n`.
fn proper(n: &Number, f: &Number) {
    assert!(f.byte_order() == n.byte_order(), "the byte order of n");
    assert!(*f > 1u8 && *f < n.abs(), "{f} is a proper factor of {n}");
    assert!((n % f).is_zero(), "{f} divides {n}");
}

#[test]
fn pm1_continuation_finds_the_prime() {
    let cases: &[(&str, u64, u64, &str)] = if cfg!(miri) { &PM1_MIRI } else { &PM1_FOUND };
    for (i, &(s, b1, b2, p)) in cases.iter().enumerate() {
        // Both byte orders on some, a negative number on others.
        let order = ORDERS[i % 2];
        let n = num(s, order, i % 3 == 2);
        let f = factor::pm1(&n, b1, b2);
        is(&f, p, &n);
        // Stage 1 alone does not, and the same call gives the same factor.
        assert!(factor::pm1(&n, b1, 0).is_none(), "pm1({s}) in stage 1");
        if !cfg!(miri) {
            assert_eq!(factor::pm1(&n, b1, b2), f);
        }
    }
}

