/// `n = p_1 p_2` with `p_1 - 1` and `p_2 - 1` of the same large prime `q = 1469131`: every
/// continuation catches both primes with one product or one factor, and `pm1` finds nothing, as the
/// baby-step giant-step continuation did.
const SAME_Q: &str = "81845684599156800407698449028417";

#[test]
fn continuations_with_one_value_catching_two_primes() {
    if cfg!(miri) {
        return;
    }
    for (i, &(m, s, b1, b2)) in ONE_VALUE.iter().enumerate() {
        let n = num(s, ORDERS[i % 2], i % 3 == 0);
        let f = if m == "pm1" {
            factor::pm1(&n, b1, b2)
        } else {
            factor::pp1(&n, b1, b2)
        };
        proper(&n, &f.unwrap_or_else(|| panic!("{m}({s}, {b1}, {b2})")));
    }
    for (i, &(m, s)) in TOP_PAIR.iter().enumerate() {
        let n = num(s, ORDERS[i % 2], i % 3 == 2);
        let f = if m == "pm1" {
            factor::pm1(&n, 1000, 2_000_000)
        } else {
            factor::pp1(&n, 1000, 2_000_000)
        };
        proper(&n, &f.unwrap_or_else(|| panic!("{m}({s}, 1000, 2000000)")));
    }
    for order in ORDERS {
        let n = num(SAME_Q, order, false);
        assert!(factor::pm1(&n, 1000, 2_000_000).is_none(), "pm1({SAME_Q})");
    }
}

