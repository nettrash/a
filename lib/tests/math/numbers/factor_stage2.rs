/// `(method, n)`: `n = p_1 p_2`, `p_i -+ 1 = 2 s_i q_i` as [`ONE_VALUE`], at `B1 = 1000`,
/// `B2 = 2 10^6`, with `q_1 q_2` just past `B2` the largest exponent of Montgomery and Kruppa's
