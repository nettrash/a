//! Tests of the second stages of `factor::pm1`, `factor::pp1` and `factor::ecm`: Montgomery and
//! Kruppa's continuation by polynomials for `p - 1` and `p + 1`, the FFT continuation of the
//! elliptic curve method, and the baby-step giant-step continuation they replace when it costs
//! more. The vectors are PARI/GP 2.19's (`ref/gen/vectors.gp`): primes `p` with `p - 1` (or
//! `p + 1`) a product of prime powers up to `B1` and one prime in `(B1, B2]`, times a prime the
//! methods cannot find, of 1 to 24 limbs with the top limb high or low (each arithmetic: in
//! registers fully or lazily reduced, and in memory); for the curves, semiprimes whose factor the
//! baby-step giant-step continuation finds with the curves given, which the continuation by
//! polynomials, covering every number prime to `D` of the range, must find too.

use a::math::numbers::{ByteOrder, Number, factor};

use super::common::*;

/// The decimal `s` in byte order `order`, negative when `negative`.
fn num(s: &str, order: ByteOrder, negative: bool) -> Number {
    let n: Number = s.parse().unwrap();
    let mut v = n.value.clone();
    if order != n.byte_order {
        v.reverse();
    }
    Number {
        value: v,
        negative,
        byte_order: order,
    }
}

