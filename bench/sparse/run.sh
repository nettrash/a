#!/usr/bin/env bash
# The sparse scoreboard (a::math::sparse: storage and operations, Matrix Market I/O, orderings,
# Cholesky, LU, QR, Krylov solvers, eigenvalues) against SuiteSparse, Apple Accelerate (macOS),
# faer, sprs, nalgebra-sparse and SciPy.
#
#   bench/sparse/run.sh [-o OUT.tsv] [GROUP ...]
#     GROUP: ops io ordering chol lu qr iter eigen py-storage py-io py-ordering py-lu py-iter
#            py-eigen (default all); the scoreboard is assembled from every group run so far
#   QUICK=1 ...           small sizes only, 5 samples (a smoke test)
#   SPARSE_ONLY=regex     only the matrices whose names match (groups ordering .. eigen)
#   ASSEMBLE_ONLY=1 ...   no timing: assemble the scoreboard from the runs kept in $WORK/run
#   TIMEOUT (2400), TIMEOUT_PY (7200): seconds a command (the SciPy iterative and eigenvalue
#   groups run Python loops on 10^6 unknowns)
#   BENCH_MEM_GB=n        the memory the probe may assume (default: MemAvailable of /proc/meminfo,
#                         or hw.memsize on macOS); a matrix of chol whose measured peak (src/g_chol.rs,
#                         peak_gb), with a quarter more, exceeds it is skipped, with rows saying so
#
# Each group is one timed command (bench/slot.sh); inside a group every matrix is its own process
# with its own timeout. The matrices are generated by the probe; the SciPy groups write their
# Matrix Market files into $WORK. References: SuiteSparse (CHOLMOD, UMFPACK, KLU, SPQR, CXSparse,
# AMD, CAMD, COLAMD, LDL; required: the area is skipped without it), single-threaded OpenBLAS;
# Apple Accelerate on macOS only (build.rs checks the target); faer, sprs, nalgebra-sparse from
# crates.io; SciPy (ARPACK, SuperLU, sparsetools, fast_matrix_market) through python3 when it has
# scipy, else those groups are skipped. Ubuntu: libsuitesparse-dev python3-scipy.
AREA=sparse
. "$(cd "$(dirname "$0")/.." && pwd)/common.sh"
set +e  # a failed command loses its rows, not the run
# Single-threaded references: OpenBLAS (SuiteSparse, numpy), OpenMP (CHOLMOD), vecLib.
export OPENBLAS_NUM_THREADS=1 OMP_NUM_THREADS=1 VECLIB_MAXIMUM_THREADS=1 MKL_NUM_THREADS=1
export BENCH_ROW_BUDGET_S=${BENCH_ROW_BUDGET_S:-40}
QUICK=${QUICK:-}
QFLAG=""
if [ -n "$QUICK" ]; then
  QFLAG="--quick"
  export BENCH_SAMPLES=${BENCH_SAMPLES:-5}
fi
ALL="ops io ordering chol lu qr iter eigen py-storage py-io py-ordering py-lu py-iter py-eigen"
SEL=${*:-$ALL}
[ -n "${ASSEMBLE_ONLY:-}" ] && SEL=""
RUN=$WORK/run
mkdir -p "$RUN"
T=${TIMEOUT:-2400}
T_PY=${TIMEOUT_PY:-7200}

if [ -n "$SEL" ]; then
  if ! have_header cholmod.h CHOLMOD && ! have_header suitesparse/cholmod.h CHOLMOD; then
    empty_board "SuiteSparse (cholmod.h) not found"
    exit 0
  fi
  echo "[sparse] building" >&2
  cargo build --release --manifest-path "$AREA_DIR/Cargo.toml" || exit 1
  cargo build --release --manifest-path "$AREA_DIR/pyffi/Cargo.toml" || exit 1
  built
fi
BIN=$CARGO_TARGET_DIR/release/sparse-bench
LIB=$CARGO_TARGET_DIR/release/libsparse_ours_ffi.dylib
[ -f "$LIB" ] || LIB=$CARGO_TARGET_DIR/release/libsparse_ours_ffi.so
HAVE_SCIPY=0
python3 -c "import scipy, numpy" 2>/dev/null && HAVE_SCIPY=1

# The matrices a group visits (BENCH_LIST prints them; nothing is timed).
names() { BENCH_LIST=1 "$BIN" "$1" $QFLAG 2>/dev/null | awk '!seen[$0]++' | grep -E "${SPARSE_ONLY:-.}"; }

# Adds one command to the group's batch: its rows go to $RUN/<tag>.tsv, its log to <tag>.err;
# the tags of a group, in order, to $RUN/<group>.order.
add() {
  local tag=$1
  shift
  echo "$tag" >> "$RUN/$CUR.order"
  printf 'echo "[sparse] %s" >&2\n' "$tag" >> "$BATCH"
  if command -v timeout >/dev/null 2>&1; then printf 'timeout %s' "${TT:-$T}" >> "$BATCH"; fi
  printf ' %q' "$@" >> "$BATCH"
  printf ' > %q 2> %q || echo "[sparse] FAILED %s (see %s)" >&2\n' "$RUN/$tag.tsv" "$RUN/$tag.err" "$tag" "$RUN/$tag.err" >> "$BATCH"
}

for g in $SEL; do
  CUR=$g
  BATCH=$RUN/$g.batch.sh
  : > "$RUN/$g.order"
  : > "$BATCH"
  case $g in
    ops)
      for p in spmv spmm spgemm transpose assembly misc; do
        add "ops-$p" env BENCH_PART="$p" "$BIN" ops $QFLAG
      done ;;
    io) add io "$BIN" io $QFLAG ;;
    ordering|chol|lu|qr|iter|eigen)
      for m in $(names "$g"); do
        add "$g-$m" env BENCH_ONLY="$m" "$BIN" "$g" $QFLAG
      done ;;
    py-*)
      if [ $HAVE_SCIPY = 1 ]; then
        TT=$T_PY add "$g" python3 "$AREA_DIR/py/scipy_ref.py" "$BIN" "$LIB" "$WORK" "${g#py-}" $QFLAG
      else
        echo "[sparse] no scipy: skipping $g" >&2
        rm -f "$RUN/$g.order"
        continue
      fi ;;
    *) echo "[sparse] unknown group $g" >&2; continue ;;
  esac
  echo "[sparse] group $g: $(wc -l < "$RUN/$g.order") commands" >&2
  slot bash "$BATCH"
done

# The scoreboard: every group that has been run (this time or before), in the canonical order.
{
  header
  for g in $ALL; do
    [ -f "$RUN/$g.order" ] || continue
    while read -r tag; do
      [ -f "$RUN/$tag.tsv" ] && grep $'^sparse\t' "$RUN/$tag.tsv"
    done < "$RUN/$g.order"
  done
} > "$OUT.partial" && mv "$OUT.partial" "$OUT"
echo "bench/$AREA: $(($(wc -l < "$OUT") - 1)) rows in $OUT" >&2
